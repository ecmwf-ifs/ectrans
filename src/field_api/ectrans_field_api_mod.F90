SUBROUTINE SET_IVSET(YLFV, IVSET, IVSET_DIM)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  INTEGER(C_INT), TARGET, ALLOCATABLE, INTENT(IN) :: IVSET(:)
  INTEGER(C_INT), INTENT(IN) :: IVSET_DIM
  IF (IVSET_DIM > 0) THEN
    CALL FIELD_VIEW_SET_IVSET_PTR(YLFV, IVSET)
  ELSE
    CALL FIELD_VIEW_SET_IVSET_PTR(YLFV)
  ENDIF
  CALL FIELD_VIEW_SET_IVSET_DIM(YLFV, IVSET_DIM)
END SUBROUTINE

