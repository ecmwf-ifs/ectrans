SUBROUTINE LG2RB(LG2RBV,YLF,IVSET)
  ! Creation of a list of GRID_VIEW encapsulating the layer of an input FIELD_2RB field
  ! Given YLF dimensioned(NPROMA, NBLKS) as input,
  ! the output list size will contain one element, its view beeing dimensioned(NPROMA, NBLKS)
  CLASS (FIELD_VIEW), POINTER, INTENT (IN) :: YLF
  TYPE (GRID_VIEW), INTENT(INOUT) :: LG2RBV (:)
  INTEGER(KIND=JPIM), POINTER, INTENT(IN) :: IVSET(:)
  REAL(KIND=JPRB), POINTER :: ZZ2 (:,:)

  CALL FIELD_VIEW_GET_DATA_PTR(YLF, ZZ2)

  IF (SIZE(LG2RBV) /= 1 ) CALL ABOR1("Error - incorrect size for LG2RBV")

  LG2RBV (1)%P => ZZ2(:,:)
  CALL COPY_NAME(YLF,LG2RBV(1)%NAME)
  IF (ASSOCIATED(IVSET)) THEN
    LG2RBV (1)%IVSET = IVSET(1)
  ELSE
    LG2RBV (1)%IVSET = 1 ! default value when IVSET is not provided
  ENDIF
END SUBROUTINE LG2RB

SUBROUTINE LG3RB(LG3RBV,YLF,IVSET)
  ! Creation of a list of GRID_VIEW encapsulating the layers of an input FIELD_3RB field
  ! Given YLF dimensioned(NPROMA, NLEVS, NBLKS) as input,
  ! the output list size will contain  (NLEVS) elements, their view beeing dimensioned(NPROMA, NBLKS)
  CLASS (FIELD_VIEW), POINTER, INTENT (IN) :: YLF
  TYPE (GRID_VIEW), INTENT(INOUT) :: LG3RBV (:)
  INTEGER(KIND=JPIM), POINTER, INTENT(IN) :: IVSET(:)

  REAL(KIND=JPRB), POINTER :: ZZ3 (:,:,:)
  INTEGER(KIND=JPIM) :: JLEV, JCOUNT

  CALL FIELD_VIEW_GET_DATA_PTR(YLF, ZZ3)

  IF (SIZE(LG3RBV) /= SIZE (ZZ3, 2) ) CALL ABOR1("Error - incorrect size for LG3RBV")

  IF (ASSOCIATED(IVSET)) THEN
    IF (SIZE(IVSET) /= SIZE(ZZ3, 2)) THEN
      CALL ABOR1("Error - LG3RB: incorrect size for IVSET: SIZE(IVSET) = " // TRIM(TO_STR(SIZE(IVSET))) &
        // " but SIZE(ZZ3, 2) = " // TRIM(TO_STR(SIZE(ZZ3, 2))))
    END IF
  END IF

  JCOUNT = 1
  DO JLEV = LBOUND (ZZ3, 2), UBOUND (ZZ3, 2)
    LG3RBV (JCOUNT)%P => ZZ3 (:, JLEV, :)
    CALL COPY_NAME(YLF,LG3RBV(JCOUNT)%NAME)
    IF (ASSOCIATED(IVSET)) THEN
      LG3RBV (JCOUNT)%IVSET = IVSET(JLEV)
    ELSE
      LG3RBV (JCOUNT)%IVSET = 1 ! default value when IVSET is not provided
    ENDIF
    JCOUNT = JCOUNT + 1
  ENDDO
CONTAINS
  FUNCTION TO_STR(I) RESULT(STR_OUT)
    INTEGER, INTENT(IN) :: I
    CHARACTER(LEN=16) :: STR_OUT
    WRITE(STR_OUT, '(I0)') I
  END FUNCTION
END SUBROUTINE LG3RB

SUBROUTINE LG4RB(LG4RBV, YLF, IVSET)
  ! Creation of a list of GRID_VIEW encapsulating the layers of an input FIELD_4RB field
  ! Given YLF dimensioned(NPROMA, NLEVS, NFIELDS, NBLKS) as input,
  ! the output list size will contain  (NLEVS*NFIELDS) elementa, their view beeing dimensioned(NPROMA, NBLKS)

  CLASS (FIELD_VIEW), INTENT(IN), POINTER :: YLF
  TYPE (GRID_VIEW), INTENT(INOUT) :: LG4RBV (:)
  INTEGER(KIND=JPIM), POINTER, INTENT(IN) :: IVSET(:)

  REAL(KIND=JPRB), POINTER :: ZZ4 (:,:,:,:)
  INTEGER(KIND=JPIM) :: JLEV, JFLD, JCOUNT

  CALL FIELD_VIEW_GET_DATA_PTR(YLF, ZZ4)

  IF (SIZE(LG4RBV) /= SIZE (ZZ4, 2) * SIZE (ZZ4, 3) ) CALL ABOR1("Error - incorrect size for LG4RBV")

  IF (ASSOCIATED(IVSET)) THEN
    IF (SIZE(IVSET) /= SIZE(ZZ4, 2)) THEN
      CALL ABOR1("Error - LG4RB: incorrect size for IVSET: SIZE(IVSET) = " // TRIM(TO_STR(SIZE(IVSET))) &
        // " but SIZE(ZZ4, 2) = " // TRIM(TO_STR(SIZE(ZZ4, 2))))
    END IF
  END IF

  JCOUNT = 1

  DO JFLD = LBOUND (ZZ4, 3), UBOUND (ZZ4, 3)
    DO JLEV = LBOUND (ZZ4, 2), UBOUND (ZZ4, 2)
      LG4RBV (JCOUNT)%P => ZZ4(:, JLEV, JFLD, :)
      CALL COPY_NAME(YLF,LG4RBV(JCOUNT)%NAME)
      IF (ASSOCIATED(IVSET)) THEN
        LG4RBV (JCOUNT)%IVSET = IVSET(JLEV)
      ELSE
        LG4RBV (JCOUNT)%IVSET = 1 ! default value when IVSET is not provided
      ENDIF
      JCOUNT = JCOUNT + 1
    ENDDO
  ENDDO
CONTAINS
  FUNCTION TO_STR(I) RESULT(STR_OUT)
    INTEGER, INTENT(IN) :: I
    CHARACTER(LEN=16) :: STR_OUT
    WRITE(STR_OUT, '(I0)') I
  END FUNCTION
END SUBROUTINE LG4RB

FUNCTION LG(YLFL,LGV,IVSET) RESULT(IOFF)
  ! Creation of a list of GRID_VIEW from a list YLFL of FIELD_VIEW
  ! For each field of YLFL, the IVSET of the matching spectral field can be provided
  ! through the optional IVSET argument. If IVSET is not provided, the IVSET of the
  ! generated GRID_VIEW is set to a default value (1).
  TYPE (FIELD_VIEW),TARGET, INTENT(IN) :: YLFL (:)      ! input list of FIELD_VIEW
  TYPE (GRID_VIEW), INTENT(INOUT), OPTIONAL :: LGV (:) ! output list of GRID_VIEW
  TYPE (IVSET_PTR), INTENT(IN), OPTIONAL :: IVSET(:)

  CLASS (FIELD_VIEW), POINTER:: YLF
  INTEGER(KIND=JPIM), POINTER :: IVSET_NULL(:)
  INTEGER(KIND=JPIM) :: IOFF
  INTEGER(KIND=JPIM) :: ILEN, JFLD
  LOGICAL :: LGV_PROVIDED

  LGV_PROVIDED = .FALSE.
  IVSET_NULL => NULL()

  IF (PRESENT(LGV)) LGV_PROVIDED = .TRUE.
  IF (PRESENT(LGV)) THEN
    IF (PRESENT(IVSET)) THEN
      IF (SIZE(YLFL) /= SIZE(IVSET)) CALL ABOR1("LG FAILURE: SIZE(YLFL) /= SIZE(IVSET)")
    ENDIF
  ENDIF

  IOFF = 0
  ILEN = -1

  ! iterate over YLFL LIST
  DO JFLD = 1, SIZE (YLFL)
  ! compute number of GRID_VIEW that will be generated for each field of the list
  ! In addition if LGV_PROVIDED: call the correct routine to create the GRID_VIEW for each field of the list
    YLF => YLFL (JFLD)
    SELECT CASE (YLF%RANK)
      CASE (1)
        ILEN = 1
      CASE (2)
        ILEN = 1
        IF (LGV_PROVIDED) THEN
          IF (PRESENT(IVSET)) THEN
            CALL LG2RB(LGV(IOFF+1:IOFF+ILEN),YLF,IVSET(JFLD)%PTR)
          ELSE
            CALL LG2RB(LGV(IOFF+1:IOFF+ILEN),YLF,IVSET_NULL)
          ENDIF
        ENDIF
      CASE(3)
        ILEN = YLF%EXTENTS(2)
        IF (LGV_PROVIDED) THEN
          IF (PRESENT(IVSET)) THEN
            CALL LG3RB(LGV (IOFF+1:IOFF+ILEN),YLF,IVSET(JFLD)%PTR)
          ELSE
            CALL LG3RB(LGV (IOFF+1:IOFF+ILEN),YLF,IVSET_NULL)
          ENDIF
        ENDIF
      CASE(4)
        ILEN =  YLF%EXTENTS(2) * YLF%EXTENTS(3)
        IF (LGV_PROVIDED) THEN
          IF (PRESENT(IVSET)) THEN
            CALL LG4RB(LGV (IOFF+1:IOFF+ILEN),YLF,IVSET(JFLD)%PTR)
          ELSE
            CALL LG4RB(LGV (IOFF+1:IOFF+ILEN),YLF,IVSET_NULL)
          ENDIF
        ENDIF
      CASE DEFAULT
        CALL ABOR1("LG FAILURE: CLASS UNKNOWN")
    END SELECT
    IOFF = IOFF + ILEN
  ENDDO

  IF (LGV_PROVIDED) THEN
    IF (SIZE(LGV) /= IOFF)  CALL ABOR1("LG FAILURE: LSV has incorrect size")
  ENDIF

END FUNCTION LG

FUNCTION LG_COUNT(YLFL)
  TYPE (FIELD_VIEW), INTENT(IN) :: YLFL (:)
  INTEGER(KIND=JPIM) :: LG_COUNT
  LG_COUNT = LG(YLFL)
END FUNCTION LG_COUNT


SUBROUTINE LS1RB(LS1RBV, YLF)
  ! Creation of a list of SPEC_VIEW encapsulating the layer of an input FIELD_1RB field
  ! Given YLF dimensioned(NSPEC) as input,
  ! the output list size will contain one element, its view beeing dimensioned(NSPEC)
  CLASS (FIELD_VIEW), POINTER, INTENT (IN) :: YLF
  TYPE (SPEC_VIEW), INTENT(INOUT) :: LS1RBV (:)
  INTEGER(KIND=JPIM), POINTER :: IVSET(:)
  REAL(KIND=JPRB), POINTER :: ZZ1 (:)

  CALL GET_IVSET(YLF, IVSET)
  CALL FIELD_VIEW_GET_DATA_PTR(YLF, ZZ1)

  IF (SIZE(LS1RBV) /= 1 ) CALL ABOR1("Error - incorrect size for LS1RBV")
  LS1RBV(1)%P => ZZ1(:)
  CALL COPY_NAME(YLF,LS1RBV(1)%NAME)

END SUBROUTINE LS1RB

SUBROUTINE LS2RB(LS2RBV,YLF)
  ! Creation of a list of SPEC_VIEW, each of them encapsulating a layer of an input FIELD_2RB field.
  ! Given YLF dimensioned(NLEVS, NSPEC) as input,
  ! the output list size will contain (NLEVS) elements dimensioned(NSPEC)
  CLASS (FIELD_VIEW), POINTER, INTENT (IN) :: YLF
  TYPE (SPEC_VIEW), INTENT(INOUT) :: LS2RBV (:)

  INTEGER(KIND=JPIM), POINTER :: IVSET(:)
  REAL(KIND=JPRB), POINTER :: ZZ2 (:,:)
  INTEGER(KIND=JPIM) :: JLEV, JCOUNT

  CALL GET_IVSET(YLF, IVSET)
  CALL FIELD_VIEW_GET_DATA_PTR(YLF, ZZ2)

  IF (SIZE(LS2RBV) /= SIZE (ZZ2, 1) ) CALL ABOR1("Error - incorrect size for LS2RBV")
  JCOUNT = 1

  DO JLEV = LBOUND (ZZ2, 1), UBOUND (ZZ2, 1)
    LS2RBV (JCOUNT)%P => ZZ2 (JLEV, :)
    CALL COPY_NAME(YLF,LS2RBV(JCOUNT)%NAME)
    JCOUNT = JCOUNT + 1
  ENDDO

END SUBROUTINE LS2RB

SUBROUTINE LS3RB(LS3RBV,YLF)
  ! Creation of a list of SPEC_VIEW, each of them encapsulating a layer of an input FIELD_3RB field.
  ! Given YLF dimensioned(NLEVS, NSPEC, NFIELDS) as input,
  ! the output list size will contain (NLEVS*NFIELDS) SPEC_VIEW, each of them dimensioned(NSPEC)
  CLASS (FIELD_VIEW), POINTER, INTENT (IN) :: YLF
  TYPE (SPEC_VIEW), INTENT(INOUT) :: LS3RBV (:)

  INTEGER(KIND=JPIM), POINTER :: IVSET(:)
  REAL(KIND=JPRB), POINTER :: ZZ3 (:,:,:)

  INTEGER(KIND=JPIM) :: JLEV, JFLD, JCOUNT

  CALL GET_IVSET(YLF, IVSET)
  CALL FIELD_VIEW_GET_DATA_PTR(YLF, ZZ3)

  IF (SIZE(LS3RBV) /=SIZE (ZZ3, 1) * SIZE (ZZ3, 3) ) CALL ABOR1("Error - incorrect size for LS3RBV")

  JCOUNT = 1

  DO JFLD = LBOUND (ZZ3, 3), UBOUND (ZZ3, 3)
    DO JLEV = LBOUND (ZZ3, 1), UBOUND (ZZ3, 1)
      LS3RBV(JCOUNT)%P => ZZ3 (JLEV, :, JFLD)
      CALL COPY_NAME(YLF,LS3RBV(JCOUNT)%NAME)
      JCOUNT = JCOUNT + 1
    ENDDO
  ENDDO

END SUBROUTINE LS3RB

FUNCTION LS(YLFL,LSV) RESULT(IOFF)
! Creation of a list of SPEC_VIEW from a list YLFL of FIELD_BASIC_PTR
TYPE (FIELD_VIEW), TARGET, INTENT(IN) :: YLFL (:) ! input list of FIELD_BASIC_PTR
TYPE (SPEC_VIEW), INTENT(INOUT), OPTIONAL :: LSV (:)        ! output list of SPEC_VIEW
INTEGER(KIND=JPIM) :: IOFF

INTEGER(KIND=JPIM) :: ILEN, JFLD

CLASS (FIELD_VIEW), POINTER:: YLF
LOGICAL :: LSV_PROVIDED
REAL(KIND=JPRB), POINTER :: ZZ1 (:)

LSV_PROVIDED = .FALSE.
IF (PRESENT(LSV))LSV_PROVIDED = .TRUE.

IOFF = 0
ILEN = -1

! iterate over YLFL LIST
DO JFLD = 1, SIZE (YLFL)
  ! compute number of SPEC_VIEW that will be generated for each field of the list
  ! in addition when LSV_PROVIDED: call the correct routine to create the SPEC_VIEW for each field of the list
  YLF => YLFL (JFLD)
  SELECT CASE (YLF%RANK)
    CASE (1)
      ILEN = 1
      IF (LSV_PROVIDED) CALL LS1RB(LSV(IOFF+1:IOFF+ILEN),YLF)
    CASE (2)
      ! Shape (NLEVS, NSPEC) -> NLEVS SPEC_VIEW of size NSPEC
      ILEN = YLF%EXTENTS(1)
      IF (LSV_PROVIDED) CALL LS2RB(LSV(IOFF+1:IOFF+ILEN),YLF)
   CASE (3)
      ! Shape (NLEVS, NSPEC, NFIELDS) -> NLEVS*NFIELDS SPEC_VIEW of size NSPEC
      ILEN = YLF%EXTENTS(1) * YLF%EXTENTS(3)
      IF (LSV_PROVIDED) CALL LS3RB(LSV(IOFF+1:IOFF+ILEN),YLF)
    CASE (4)
        CALL ABOR1("LS not implemeted for FIELD_4RB")
    case DEFAULT
        ! Skip the spectral field as it is not present on this processor
        ILEN = 1
  END SELECT

  IOFF = IOFF + ILEN
ENDDO

IF (LSV_PROVIDED ) THEN
  IF (SIZE(LSV) /= IOFF)  CALL ABOR1("LS FAILURE: LSV has incorrect size")
ENDIF

END FUNCTION LS

FUNCTION LS_COUNT(YLFL)
  TYPE (FIELD_VIEW), INTENT(IN) :: YLFL (:)
  INTEGER(KIND=JPIM) :: LS_COUNT

  LS_COUNT = LS(YLFL)
END FUNCTION LS_COUNT

SUBROUTINE SET_STRIDES_1RB(ARRAY, STRIDES)
  REAL(JPRB), POINTER :: ARRAY(:)
  INTEGER(C_INT), INTENT(OUT) :: STRIDES(:)
  TYPE(C_PTR) :: ADDR1, ADDR2
  INTEGER(C_INTPTR_T) :: STRIDE_BYTES
  STRIDES(:) = 0
  IF (SIZE(ARRAY) == 1) THEN
    STRIDES(1) = 1
    RETURN
  ENDIF
  ! At this code location we can be sure that there is more than 1 element in the array
  ADDR1 = C_LOC(ARRAY(1))
  ADDR2 = C_LOC(ARRAY(2))
  STRIDE_BYTES = TRANSFER(ADDR2, STRIDE_BYTES) - TRANSFER(ADDR1, STRIDE_BYTES)
  STRIDES(1) = STRIDE_BYTES / (STORAGE_SIZE(ARRAY) / 8)
END SUBROUTINE

SUBROUTINE SET_STRIDES_2RB(ARRAY, STRIDES)
  REAL(JPRB), POINTER :: ARRAY(:,:)
  INTEGER(C_INT), INTENT(OUT) :: STRIDES(:)
  TYPE(C_PTR) :: ADDR1, ADDR2
  INTEGER(C_INTPTR_T) :: STRIDE_BYTES
  IF (SIZE(ARRAY) == 0) THEN
    STRIDES(:) = 0
    RETURN
  ENDIF
  IF (SIZE(ARRAY) == 1) THEN
    STRIDES(:) = 1
    RETURN
  ENDIF
  ! At this code location we can be sure that there is more than 1 element in the array
  ADDR1 = C_LOC(ARRAY(1,1))

  ! Find STRIDES(1)
  IF (SIZE(ARRAY, 1) > 1) THEN
    ADDR2 = C_LOC(ARRAY(2,1))
  ELSE IF (SIZE(ARRAY, 2) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,2))
  ELSE
    CALL ABOR1("We should not be here, as SIZE(ARRAY) > 1")
  ENDIF
  STRIDE_BYTES = TRANSFER(ADDR2, STRIDE_BYTES) - TRANSFER(ADDR1, STRIDE_BYTES)
  STRIDES(1) = STRIDE_BYTES / (STORAGE_SIZE(ARRAY) / 8)

  ! Find STRIDES(2)
  IF (SIZE(ARRAY, 2) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,2))
    STRIDE_BYTES = TRANSFER(ADDR2, STRIDE_BYTES) - TRANSFER(ADDR1, STRIDE_BYTES)
    STRIDES(2) = STRIDE_BYTES / (STORAGE_SIZE(ARRAY) / 8)
  ELSE
    STRIDES(2) = STRIDES(1) * SIZE(ARRAY, 1)
  ENDIF
END SUBROUTINE

SUBROUTINE SET_STRIDES_3RB(ARRAY, STRIDES)
  REAL(JPRB), POINTER :: ARRAY(:,:,:)
  INTEGER(C_INT), INTENT(OUT) :: STRIDES(:)
  TYPE(C_PTR) :: ADDR1, ADDR2
  INTEGER(C_INTPTR_T) :: STRIDE_BYTES
  IF (SIZE(ARRAY) == 0) THEN
    STRIDES(:) = 0
    RETURN
  ENDIF
  IF (SIZE(ARRAY) == 1) THEN
    STRIDES(:) = 1
    RETURN
  ENDIF
  ! At this code location we can be sure that there is more than 1 element in the array
  ADDR1 = C_LOC(ARRAY(1,1,1))

  ! Find STRIDES(1)
  IF (SIZE(ARRAY, 1) > 1) THEN
    ADDR2 = C_LOC(ARRAY(2,1,1))
  ELSE IF (SIZE(ARRAY, 2) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,2,1))
  ELSE IF (SIZE(ARRAY, 3) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,1,2))
  ELSE
    CALL ABOR1("We should not be here, as SIZE(ARRAY) > 1")
  ENDIF
  STRIDE_BYTES = TRANSFER(ADDR2, STRIDE_BYTES) - TRANSFER(ADDR1, STRIDE_BYTES)
  STRIDES(1) = STRIDE_BYTES / (STORAGE_SIZE(ARRAY) / 8)

  ! Find STRIDES(2)
  IF (SIZE(ARRAY, 2) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,2,1))
    STRIDE_BYTES = TRANSFER(ADDR2, STRIDE_BYTES) - TRANSFER(ADDR1, STRIDE_BYTES)
    STRIDES(2) = STRIDE_BYTES / (STORAGE_SIZE(ARRAY) / 8)
  ELSE
    STRIDES(2) = STRIDES(1) * SIZE(ARRAY, 1)
  ENDIF

  ! Find STRIDES(3)
  IF (SIZE(ARRAY, 3) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,1,2))
    STRIDE_BYTES = TRANSFER(ADDR2, STRIDE_BYTES) - TRANSFER(ADDR1, STRIDE_BYTES)
    STRIDES(3) = STRIDE_BYTES / (STORAGE_SIZE(ARRAY) / 8)
  ELSE
    STRIDES(3) = STRIDES(2) * SIZE(ARRAY, 2)
  ENDIF
END SUBROUTINE

SUBROUTINE SET_STRIDES_4RB(ARRAY, STRIDES)
  REAL(JPRB), POINTER :: ARRAY(:,:,:,:)
  INTEGER(C_INT), INTENT(OUT) :: STRIDES(:)
  TYPE(C_PTR) :: ADDR1, ADDR2
  INTEGER(C_INTPTR_T) :: STRIDE_BYTES
  IF (SIZE(ARRAY) == 0) THEN
    STRIDES(:) = 0
    RETURN
  ENDIF
  IF (SIZE(ARRAY) == 1) THEN
    STRIDES(:) = 1
    RETURN
  ENDIF
  ! At this code location we can be sure that there is more than 1 element in the array
  ADDR1 = C_LOC(ARRAY(1,1,1,1))

  ! Find STRIDES(1)
  IF (SIZE(ARRAY, 1) > 1) THEN
    ADDR2 = C_LOC(ARRAY(2,1,1,1))
  ELSE IF (SIZE(ARRAY, 2) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,2,1,1))
  ELSE IF (SIZE(ARRAY, 3) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,1,2,1))
  ELSE IF (SIZE(ARRAY, 4) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,1,1,2))
  ELSE
    CALL ABOR1("We should not be here, as SIZE(ARRAY) > 1")
  ENDIF
  STRIDE_BYTES = TRANSFER(ADDR2, STRIDE_BYTES) - TRANSFER(ADDR1, STRIDE_BYTES)
  STRIDES(1) = STRIDE_BYTES / (STORAGE_SIZE(ARRAY) / 8)

  ! Find STRIDES(2)
  IF (SIZE(ARRAY, 2) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,2,1,1))
    STRIDE_BYTES = TRANSFER(ADDR2, STRIDE_BYTES) - TRANSFER(ADDR1, STRIDE_BYTES)
    STRIDES(2) = STRIDE_BYTES / (STORAGE_SIZE(ARRAY) / 8)
  ELSE
    STRIDES(2) = STRIDES(1) * SIZE(ARRAY, 1)
  ENDIF

  ! Find STRIDES(3)
  IF (SIZE(ARRAY, 3) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,1,2,1))
    STRIDE_BYTES = TRANSFER(ADDR2, STRIDE_BYTES) - TRANSFER(ADDR1, STRIDE_BYTES)
    STRIDES(3) = STRIDE_BYTES / (STORAGE_SIZE(ARRAY) / 8)
  ELSE
    STRIDES(3) = STRIDES(2) * SIZE(ARRAY, 2)
  ENDIF

  ! Find STRIDES(4)
  IF (SIZE(ARRAY, 4) > 1) THEN
    ADDR2 = C_LOC(ARRAY(1,1,1,2))
    STRIDE_BYTES = TRANSFER(ADDR2, STRIDE_BYTES) - TRANSFER(ADDR1, STRIDE_BYTES)
    STRIDES(4) = STRIDE_BYTES / (STORAGE_SIZE(ARRAY) / 8)
  ELSE
    STRIDES(4) = STRIDES(3) * SIZE(ARRAY, 3)
  ENDIF
END SUBROUTINE


SUBROUTINE SET_EXTENTS_1RB(ARRAY, EXTENTS)
  REAL(JPRB), POINTER :: ARRAY(:)
  INTEGER(C_INT), INTENT(OUT) :: EXTENTS(:)
  EXTENTS = 0
  EXTENTS(1) = SIZE(ARRAY)
END SUBROUTINE

SUBROUTINE SET_EXTENTS_2RB(ARRAY, EXTENTS)
  REAL(JPRB), POINTER :: ARRAY(:,:)
  INTEGER(C_INT), INTENT(OUT) :: EXTENTS(:)
  EXTENTS = 0
  EXTENTS(1) = SIZE(ARRAY,1)
  EXTENTS(2) = SIZE(ARRAY,2)
END SUBROUTINE

SUBROUTINE SET_EXTENTS_3RB(ARRAY, EXTENTS)
  REAL(JPRB), POINTER :: ARRAY(:,:,:)
  INTEGER(C_INT), INTENT(OUT) :: EXTENTS(:)
  EXTENTS = 0
  EXTENTS(1) = SIZE(ARRAY,1)
  EXTENTS(2) = SIZE(ARRAY,2)
  EXTENTS(3) = SIZE(ARRAY,3)
END SUBROUTINE

SUBROUTINE SET_EXTENTS_4RB(ARRAY, EXTENTS)
  REAL(JPRB), POINTER :: ARRAY(:,:,:,:)
  INTEGER(C_INT), INTENT(OUT) :: EXTENTS(:)
  EXTENTS = 0
  EXTENTS(1) = SIZE(ARRAY,1)
  EXTENTS(2) = SIZE(ARRAY,2)
  EXTENTS(3) = SIZE(ARRAY,3)
  EXTENTS(4) = SIZE(ARRAY,4)
END SUBROUTINE




SUBROUTINE SET_DATA_RDWR_1RB(YLFV, FIELD, LDACC, LDRDONLY)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  CLASS(FIELD_1RB), POINTER, INTENT(IN) :: FIELD
  LOGICAL, INTENT(IN) :: LDACC
  LOGICAL, INTENT(IN) :: LDRDONLY
  REAL(JPRB), POINTER :: PTR(:)
  IF (LDACC) THEN
    IF (LDRDONLY) THEN
      CALL FIELD%GET_DEVICE_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_DEVICE_DATA_RDWR(PTR)
    ENDIF
  ELSE
    IF (LDRDONLY) THEN
      CALL FIELD%GET_HOST_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_HOST_DATA_RDWR(PTR)
    ENDIF
  ENDIF
  YLFV%DATA = C_LOC(PTR(1))
  YLFV%KIND_SIZE = STORAGE_SIZE(PTR) / 8
  YLFV%RANK = 1
  CALL SET_EXTENTS_1RB(PTR, YLFV%EXTENTS)
  CALL SET_STRIDES_1RB(PTR, YLFV%STRIDES)
END SUBROUTINE

SUBROUTINE SET_DATA_RDWR_2RB(YLFV, FIELD, LDACC, LDRDONLY)
