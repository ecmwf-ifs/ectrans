SUBROUTINE PREVENT_COMPILER_OPTIMISATION(F)
  TYPE(FIELD_SPEC), TARGET, INTENT(INOUT) :: F
  INTEGER(KIND=JPIM), POINTER, VOLATILE, SAVE :: IVSET_DUMMY(:)
  IF (ALLOCATED(F%IVSET)) THEN
    IVSET_DUMMY => F%IVSET
  ELSE
    IVSET_DUMMY => NULL()
  END IF
END SUBROUTINE PREVENT_COMPILER_OPTIMISATION

FUNCTION MAKE_FIELD_SPEC_1RB(YLF,NAME,IVSET)
  ! Creation of a FIELD_SPEC encapsulating a FIELD_1RB field
  TYPE (FIELD_SPEC) :: MAKE_FIELD_SPEC_1RB
  CLASS (FIELD_1RB), INTENT(IN), POINTER :: YLF
  CHARACTER(LEN=*), INTENT(IN) :: NAME
  INTEGER(KIND=JPIM), INTENT(IN), OPTIONAL :: IVSET(:)

  MAKE_FIELD_SPEC_1RB%PTR => YLF
  MAKE_FIELD_SPEC_1RB%NAME = NAME
  IF (PRESENT(IVSET)) THEN
    ALLOCATE(MAKE_FIELD_SPEC_1RB%IVSET(SIZE(IVSET)))
    MAKE_FIELD_SPEC_1RB%IVSET = IVSET
  ENDIF
  CALL PREVENT_COMPILER_OPTIMISATION(MAKE_FIELD_SPEC_1RB)
END FUNCTION MAKE_FIELD_SPEC_1RB

