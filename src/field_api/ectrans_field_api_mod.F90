SUBROUTINE MAKE_FIELD_VIEW_SPEC(YLFV, YLF, LDACC, LDRDONLY)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  TYPE(FIELD_SPEC), INTENT(IN) :: YLF
  LOGICAL, INTENT(IN) :: LDACC
  LOGICAL, INTENT(IN) :: LDRDONLY
  CALL FIELD_VIEW_INIT(YLFV)
  CALL SET_ACCESS(YLFV, LDACC, LDRDONLY)
  SELECT TYPE (FIELD => YLF%PTR)
    CLASS IS (FIELD_1RB)
      CALL SET_DATA_1RB(YLFV, FIELD, LDACC, LDRDONLY)
      YLFV%INDEXING = FIELD_VIEW_INDEXING%SPEC2
      CALL SET_IVSET(YLFV, YLF%IVSET, 0)
    CLASS IS (FIELD_2RB)
      CALL SET_DATA_2RB(YLFV, FIELD, LDACC, LDRDONLY)
      YLFV%INDEXING = FIELD_VIEW_INDEXING%LEVEL_SPEC2
      CALL SET_IVSET(YLFV, YLF%IVSET, 1)
    CLASS IS (FIELD_3RB)
      CALL SET_DATA_3RB(YLFV, FIELD, LDACC, LDRDONLY)
      YLFV%INDEXING = FIELD_VIEW_INDEXING%LEVEL_SPEC2_FIELD
      CALL SET_IVSET(YLFV, YLF%IVSET, 1)
    CLASS IS (FIELD_4RB)
      CALL ABOR1("MAKE_FIELD_VIEW FAILURE: SPECTRAL FIELDS OF RANK 4 ARE NOT SUPPORTED")
    CLASS DEFAULT
      CALL ABOR1("MAKE_FIELD_VIEW FAILURE: CLASS UNKNOWN")
  END SELECT
  CALL FIELD_VIEW_SET_NAME(YLFV, YLF%NAME)

END SUBROUTINE

SUBROUTINE MAKE_FIELD_VIEW_GRID(YLFV, YLF, LDACC, LDRDONLY)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  TYPE(FIELD_GRID), INTENT(IN) :: YLF
  LOGICAL, INTENT(IN) :: LDACC
  LOGICAL, INTENT(IN) :: LDRDONLY

  CALL FIELD_VIEW_INIT(YLFV)
  CALL SET_ACCESS(YLFV, LDACC, LDRDONLY)
  SELECT TYPE (FIELD => YLF%PTR)
    CLASS IS (FIELD_1RB)
      CALL SET_DATA_1RB(YLFV, FIELD, LDACC, LDRDONLY)
      YLFV%INDEXING = FIELD_VIEW_INDEXING%BLOCK ! Treats NPROMA=1
    CLASS IS (FIELD_2RB)
      CALL SET_DATA_2RB(YLFV, FIELD, LDACC, LDRDONLY)
      YLFV%INDEXING = FIELD_VIEW_INDEXING%NPROMA_BLOCK
    CLASS IS (FIELD_3RB)
      CALL SET_DATA_3RB(YLFV, FIELD, LDACC, LDRDONLY)
      YLFV%INDEXING = FIELD_VIEW_INDEXING%NPROMA_LEVEL_BLOCK
    CLASS IS (FIELD_4RB)
      CALL SET_DATA_4RB(YLFV, FIELD, LDACC, LDRDONLY)
      YLFV%INDEXING = FIELD_VIEW_INDEXING%NPROMA_LEVEL_FIELD_BLOCK
    CLASS DEFAULT
      CALL ABOR1("MAKE_FIELD_VIEW FAILURE: CLASS UNKNOWN")
  END SELECT
  CALL FIELD_VIEW_SET_NAME(YLFV, YLF%NAME)

END SUBROUTINE

! ------------------------------------------------------------------------------------------------
! Private helper subroutines for setting data access modes for different field types
! ------------------------------------------------------------------------------------------------

SUBROUTINE SET_ACCESS(YLFV, LDACC, LDRDONLY)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  LOGICAL, INTENT(IN) :: LDACC
  LOGICAL, INTENT(IN) :: LDRDONLY
  IF (LDACC) THEN
    IF (LDRDONLY) THEN
      CALL FIELD_VIEW_SET_ACCESS(YLFV, FIELD_VIEW_ACCESS%DEVICE, FIELD_VIEW_ACCESS%READONLY)
    ELSE
      CALL FIELD_VIEW_SET_ACCESS(YLFV, FIELD_VIEW_ACCESS%DEVICE)
    ENDIF
  ELSE
    IF (LDRDONLY) THEN
      CALL FIELD_VIEW_SET_ACCESS(YLFV, FIELD_VIEW_ACCESS%HOST, FIELD_VIEW_ACCESS%READONLY)
    ELSE
      CALL FIELD_VIEW_SET_ACCESS(YLFV, FIELD_VIEW_ACCESS%HOST)
    ENDIF
  ENDIF
END SUBROUTINE

SUBROUTINE SET_DATA_1RB(YLFV, FIELD, LDACC, LDRDONLY)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  CLASS(FIELD_1RB), POINTER, INTENT(IN) :: FIELD
  LOGICAL, INTENT(IN) :: LDACC
  LOGICAL, INTENT(IN) :: LDRDONLY
  REAL(JPRB), POINTER :: PTR(:)
  IF (LDACC) THEN
    IF (LDRDONLY) THEN
      CALL FIELD%GET_DEVICE_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_DEVICE_DATA_RDWR(PTR)
    ENDIF
  ELSE
    IF (LDRDONLY) THEN
      CALL FIELD%GET_HOST_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_HOST_DATA_RDWR(PTR)
    ENDIF
  ENDIF
  CALL FIELD_VIEW_SET_DATA_PTR(YLFV, PTR)
END SUBROUTINE

