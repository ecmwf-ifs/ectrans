SUBROUTINE SET_DATA_RDWR_1RB(YLFV, FIELD, LDACC, LDRDONLY)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  CLASS(FIELD_1RB), POINTER :: FIELD
  LOGICAL, INTENT(IN) :: LDACC
  LOGICAL, INTENT(IN) :: LDRDONLY
  REAL(JPRB), POINTER :: PTR(:)
  IF (LDACC) THEN
    IF (LDRDONLY) THEN
      CALL FIELD%GET_DEVICE_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_DEVICE_DATA_RDWR(PTR)
    ENDIF
  ELSE
    IF (LDRDONLY) THEN
      CALL FIELD%GET_HOST_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_HOST_DATA_RDWR(PTR)
    ENDIF
  ENDIF
  YLFV%DATA = C_LOC(PTR(1))
  YLFV%KIND_SIZE = STORAGE_SIZE(PTR) / 8
  YLFV%RANK = 1
  CALL SET_EXTENTS_1RB(PTR, YLFV%EXTENTS)
  CALL SET_STRIDES_1RB(PTR, YLFV%STRIDES)
END SUBROUTINE

SUBROUTINE SET_DATA_RDWR_2RB(YLFV, FIELD, LDACC, LDRDONLY)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  CLASS(FIELD_2RB), POINTER :: FIELD
  LOGICAL, INTENT(IN) :: LDACC
  LOGICAL, INTENT(IN) :: LDRDONLY
  REAL(JPRB), POINTER :: PTR(:,:)
  IF (LDACC) THEN
    IF (LDRDONLY) THEN
      CALL FIELD%GET_DEVICE_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_DEVICE_DATA_RDWR(PTR)
    ENDIF
  ELSE
    IF (LDRDONLY) THEN
      CALL FIELD%GET_HOST_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_HOST_DATA_RDWR(PTR)
    ENDIF
  ENDIF
  YLFV%DATA = C_LOC(PTR(1,1))
  YLFV%KIND_SIZE = STORAGE_SIZE(PTR) / 8
  YLFV%RANK = 2
  CALL SET_EXTENTS_2RB(PTR, YLFV%EXTENTS)
  CALL SET_STRIDES_2RB(PTR, YLFV%STRIDES)
END SUBROUTINE

SUBROUTINE SET_DATA_RDWR_3RB(YLFV, FIELD, LDACC, LDRDONLY)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  CLASS(FIELD_3RB), POINTER :: FIELD
  LOGICAL, INTENT(IN) :: LDACC
  LOGICAL, INTENT(IN) :: LDRDONLY
  REAL(JPRB), POINTER :: PTR(:,:,:)
  IF (LDACC) THEN
    IF (LDRDONLY) THEN
      CALL FIELD%GET_DEVICE_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_DEVICE_DATA_RDWR(PTR)
    ENDIF
  ELSE
    IF (LDRDONLY) THEN
      CALL FIELD%GET_HOST_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_HOST_DATA_RDWR(PTR)
    ENDIF
  ENDIF
  YLFV%DATA = C_LOC(PTR(1,1,1))
  YLFV%KIND_SIZE = STORAGE_SIZE(PTR) / 8
  YLFV%RANK = 3
  CALL SET_EXTENTS_3RB(PTR, YLFV%EXTENTS)
  CALL SET_STRIDES_3RB(PTR, YLFV%STRIDES)
END SUBROUTINE

SUBROUTINE SET_DATA_RDWR_4RB(YLFV, FIELD, LDACC, LDRDONLY)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  CLASS(FIELD_4RB), POINTER :: FIELD
  LOGICAL, INTENT(IN) :: LDACC
  LOGICAL, INTENT(IN) :: LDRDONLY
  REAL(JPRB), POINTER :: PTR(:,:,:,:)
  IF (LDACC) THEN
    IF (LDRDONLY) THEN
      CALL FIELD%GET_DEVICE_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_DEVICE_DATA_RDWR(PTR)
    ENDIF
  ELSE
    IF (LDRDONLY) THEN
      CALL FIELD%GET_HOST_DATA_RDONLY(PTR)
    ELSE
      CALL FIELD%GET_HOST_DATA_RDWR(PTR)
    ENDIF
  ENDIF
  YLFV%DATA = C_LOC(PTR(1,1,1,1))
  YLFV%KIND_SIZE = STORAGE_SIZE(PTR) / 8
  YLFV%RANK = 4
  CALL SET_EXTENTS_4RB(PTR, YLFV%EXTENTS)
  CALL SET_STRIDES_4RB(PTR, YLFV%STRIDES)
END SUBROUTINE

SUBROUTINE SET_NAME(YLFV, NAME)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  CHARACTER(LEN=*), TARGET, INTENT(IN) :: NAME
  YLFV%NAME = C_LOC(NAME(1:1))
  YLFV%NAME_SIZE = LEN_TRIM(NAME)
END SUBROUTINE

SUBROUTINE SET_FIELD_TYPE(YLFV, FIELD_TYPE)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  INTEGER, INTENT(IN) :: FIELD_TYPE
  YLFV%FIELD_TYPE = FIELD_TYPE
END SUBROUTINE

SUBROUTINE SET_IVSET(YLFV, IVSET)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  INTEGER(C_INT), TARGET, INTENT(IN) :: IVSET(:)
  YLFV%IVSET = C_LOC(IVSET(1))
  YLFV%IVSET_SIZE = SIZE(IVSET)
END SUBROUTINE


SUBROUTINE MAKE_FIELD_VIEW(YLFV, YLF, FIELD_TYPE, LDACC, LDRDONLY)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  TYPE(FIELD_BASIC_PTR), INTENT(IN) :: YLF
  INTEGER :: FIELD_TYPE
  LOGICAL, INTENT(IN) :: LDACC
  LOGICAL, INTENT(IN) :: LDRDONLY
  SELECT TYPE (FIELD => YLF%PTR)
    CLASS IS (FIELD_1RB)
      CALL SET_DATA_RDWR_1RB(YLFV, FIELD, LDACC, LDRDONLY)
    CLASS IS (FIELD_2RB)
      CALL SET_DATA_RDWR_2RB(YLFV, FIELD, LDACC, LDRDONLY)
    CLASS IS (FIELD_3RB)
      CALL SET_DATA_RDWR_3RB(YLFV, FIELD, LDACC, LDRDONLY)
    CLASS IS (FIELD_4RB)
      CALL SET_DATA_RDWR_4RB(YLFV, FIELD, LDACC, LDRDONLY)
    CLASS DEFAULT
      CALL ABOR1("MAKE_FIELD_VIEW FAILURE: CLASS UNKNOWN")
  END SELECT
  CALL SET_NAME(YLFV, YLF%NAME)
  CALL SET_FIELD_TYPE(YLFV, FIELD_TYPE)
  CALL SET_IVSET(YLFV, YLF%IVSET)
END SUBROUTINE

