SUBROUTINE PROCESS_NFLD(LIST, NFLD)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST(:)
  INTEGER(C_INT), INTENT(INOUT) :: NFLD
  INTEGER :: I
  DO I = 1, SIZE(LIST)
    IF (LIST(I)%RANK <= 2) THEN
      NFLD = NFLD + 1
    ELSE IF (LIST(I)%RANK == 3) THEN
      NFLD = NFLD + LIST(I)%EXTENTS(2)
    ELSE IF (LIST(I)%RANK == 4) THEN
      NFLD = NFLD + LIST(I)%EXTENTS(2) * LIST(I)%EXTENTS(3)
    ELSE
      CALL ABORT_TRANS("GET_NFLD FAILURE: RANK MUST BE <= 4")
    ENDIF
  ENDDO
END SUBROUTINE

FUNCTION GET_NFLD_1(LIST) RESULT(NFLD)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST(:)
  INTEGER(C_INT) :: NFLD
  NFLD = 0
  CALL PROCESS_NFLD(LIST, NFLD)
END FUNCTION

