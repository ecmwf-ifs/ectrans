INTEGER(C_INT), PARAMETER ::   &
    & MEMORY_TYPE_UNKNOWN = 0, &
    & MEMORY_TYPE_HOST    = 1, &
    & MEMORY_TYPE_DEVICE  = 2

TYPE, BIND(C) :: FIELD_VIEW

  ! ARRAY
  TYPE(C_PTR)    :: DATA
  INTEGER(C_INT) :: KIND
  INTEGER(C_INT) :: RANK
  INTEGER(C_INT) :: EXTENTS(MAX_RANK) ! NOTE: FORTRAN ORDERING
  INTEGER(C_INT) :: STRIDES(MAX_RANK) ! NOTE: FORTRAN ORDERING

  ! IVSET
  TYPE(C_PTR)    :: IVSET
  INTEGER(C_INT) :: IVSET_SIZE

  ! NAME
  TYPE(C_PTR)    :: NAME
  INTEGER(C_INT) :: NAME_SIZE

  ! FIELD TYPE
  INTEGER(C_INT) :: FIELD_TYPE

  ! INDEXING TYPE
  INTEGER(C_INT) :: INDEXING_TYPE     ! NOTE: FORTRAN ORDERING

  ! MEMORY TYPE
  INTEGER(C_INT) :: MEMORY_TYPE

END TYPE


