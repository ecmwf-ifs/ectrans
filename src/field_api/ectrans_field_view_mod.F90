SUBROUTINE PROCESS_NPROMA(LIST, NPROMA)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST(:)
  INTEGER(C_INT), INTENT(INOUT) :: NPROMA
  INTEGER :: I
  DO I = 1, SIZE(LIST)
    IF (LIST(I)%RANK == 1) THEN
      IF (NPROMA == 0) THEN
        NPROMA = 1
      ELSE IF (NPROMA /= 1) THEN
        CALL ABORT_TRANS("GET_NPROMA FAILURE: Inconsistent NPROMA values across fields")
      ENDIF
    ELSE
      IF (NPROMA == 0) THEN
        NPROMA = LIST(I)%EXTENTS(1)
      ELSE IF (NPROMA /= LIST(I)%EXTENTS(1)) THEN
        CALL ABORT_TRANS("GET_NPROMA FAILURE: Inconsistent NPROMA values across fields")
      ENDIF
    ENDIF
  ENDDO
END SUBROUTINE

FUNCTION GET_NPROMA_1(LIST) RESULT(NPROMA)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST(:)
  INTEGER(C_INT) :: NPROMA
  NPROMA = 0
  CALL PROCESS_NPROMA(LIST, NPROMA)
END FUNCTION

FUNCTION GET_NPROMA_2(LIST1, LIST2) RESULT(NPROMA)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST1(:), LIST2(:)
  INTEGER(C_INT) :: NPROMA
  NPROMA = 0
