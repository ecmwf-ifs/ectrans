FUNCTION FIELD_TYPE_TEST_1(FIELD_TYPE, TEST_MASK) RESULT(IS_SET)
  INTEGER(C_INT), INTENT(IN) :: FIELD_TYPE
  INTEGER(C_INT), INTENT(IN) :: TEST_MASK
  LOGICAL :: IS_SET
  IS_SET = (IAND(FIELD_TYPE, TEST_MASK) == TEST_MASK)
END FUNCTION

FUNCTION FIELD_TYPE_TEST_2(FIELD_TYPE, TEST_MASK1, TEST_MASK2) RESULT(IS_SET)
  INTEGER(C_INT), INTENT(IN) :: FIELD_TYPE
  INTEGER(C_INT), INTENT(IN) :: TEST_MASK1, TEST_MASK2
  LOGICAL :: IS_SET
  INTEGER(C_INT) :: COMBINED_MASK
  COMBINED_MASK = IOR(TEST_MASK1, TEST_MASK2)
  IS_SET = (IAND(FIELD_TYPE, COMBINED_MASK) == COMBINED_MASK)
END FUNCTION

FUNCTION FIELD_TYPE_TEST_3(FIELD_TYPE, TEST_MASK1, TEST_MASK2, TEST_MASK3) RESULT(IS_SET)
  INTEGER(C_INT), INTENT(IN) :: FIELD_TYPE
  INTEGER(C_INT), INTENT(IN) :: TEST_MASK1, TEST_MASK2, TEST_MASK3
  LOGICAL :: IS_SET
  INTEGER(C_INT) :: COMBINED_MASK
  COMBINED_MASK = IOR(TEST_MASK1, IOR(TEST_MASK2, TEST_MASK3))
  IS_SET = (IAND(FIELD_TYPE, COMBINED_MASK) == COMBINED_MASK)
END FUNCTION


SUBROUTINE COPY_NAME(YLFV, NAME)
  CHARACTER(LEN=*) :: NAME
  TYPE(FIELD_VIEW), INTENT(IN) :: YLFV
  CHARACTER(LEN=1), POINTER :: NAME_FPTR(:)
  INTEGER :: I
  CALL C_F_POINTER(YLFV%NAME, NAME_FPTR, [YLFV%NAME_SIZE])
  IF (LEN(NAME) < YLFV%NAME_SIZE) THEN
    CALL ABORT_TRANS("COPY_NAME FAILURE: NAME length is smaller than NAME_SIZE")
  ENDIF
  DO I = 1, YLFV%NAME_SIZE
    NAME(I:I) = NAME_FPTR(I)
  ENDDO
  DO I = YLFV%NAME_SIZE + 1, LEN(NAME)
    NAME(I:I) = " "
  ENDDO
END SUBROUTINE

SUBROUTINE GET_NAME_PTR(YLFV, NAME)
  TYPE(FIELD_VIEW), INTENT(IN) :: YLFV
  CHARACTER(LEN=:), POINTER :: NAME
  CHARACTER(LEN=YLFV%NAME_SIZE), POINTER :: F_STR
  CALL C_F_POINTER(YLFV%NAME, F_STR)
  NAME => F_STR
END SUBROUTINE

