FUNCTION GET_NFLD_1(LIST) RESULT(NFLD)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST(:)
  INTEGER(C_INT) :: NFLD
  NFLD = 0
  CALL PROCESS_LIST(LIST)
CONTAINS
  SUBROUTINE PROCESS_LIST(LIST)
    TYPE(FIELD_VIEW), INTENT(IN) :: LIST(:)
    INTEGER :: I
    DO I = 1, SIZE(LIST)
      IF (LIST(I)%RANK <= 2) THEN
        NFLD = NFLD + 1
      ELSE IF (LIST(I)%RANK == 3) THEN
        NFLD = NFLD + LIST(I)%EXTENTS(2)
      ELSE IF (LIST(I)%RANK == 4) THEN
        NFLD = NFLD + LIST(I)%EXTENTS(2) * LIST(I)%EXTENTS(3)
      ELSE
        CALL ABOR1("GET_NFLD FAILURE: RANK MUST BE <= 4") 
      ENDIF
    ENDDO
  END SUBROUTINE
END FUNCTION

FUNCTION GET_NFLD_3(LIST1, LIST2, LIST3) RESULT(NFLD)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST1(:), LIST2(:), LIST3(:)
  INTEGER(C_INT) :: NFLD
  NFLD = 0
  CALL PROCESS_LIST(LIST1)
  CALL PROCESS_LIST(LIST2)
  CALL PROCESS_LIST(LIST3)
CONTAINS
  SUBROUTINE PROCESS_LIST(LIST)
    TYPE(FIELD_VIEW), INTENT(IN) :: LIST(:)
    INTEGER :: I
    DO I = 1, SIZE(LIST)
      IF (LIST(I)%RANK <= 2) THEN
        NFLD = NFLD + 1
      ELSE IF (LIST(I)%RANK == 3) THEN
        NFLD = NFLD + LIST(I)%EXTENTS(2)
      ELSE IF (LIST(I)%RANK == 4) THEN
        NFLD = NFLD + LIST(I)%EXTENTS(2) * LIST(I)%EXTENTS(3)
      ELSE
        CALL ABOR1("GET_NFLD FAILURE: RANK MUST BE <= 4") 
      ENDIF
    ENDDO
  END SUBROUTINE
END FUNCTION


FUNCTION GET_NSPEC2_1(LIST) RESULT(NSPEC2)
  ! Return the maximum spectral dimension (NSPEC2) found in LIST.
  ! Spectral fields follow these shape conventions:
  !   rank 1: (NSPEC)                  -> NSPEC2 = EXTENTS(1)
  !   rank 2: (NLEVS, NSPEC)           -> NSPEC2 = EXTENTS(2)
  !   rank 3: (NLEVS, NSPEC, NFIELDS)  -> NSPEC2 = EXTENTS(2)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST(:)
  INTEGER(C_INT) :: NSPEC2
  INTEGER :: I
  NSPEC2 = 0
  DO I = 1, SIZE(LIST)
    IF (LIST(I)%RANK == 1) THEN
      NSPEC2 = MAX(NSPEC2, LIST(I)%EXTENTS(1))
    ELSE IF (LIST(I)%RANK == 2) THEN
      NSPEC2 = MAX(NSPEC2, LIST(I)%EXTENTS(2))
    ELSE IF (LIST(I)%RANK == 3) THEN
      NSPEC2 = MAX(NSPEC2, LIST(I)%EXTENTS(2))
    ELSE
      CALL ABOR1("GET_NSPEC2 FAILURE: RANK MUST BE <= 3")
    ENDIF
  ENDDO
END FUNCTION

FUNCTION GET_NSPEC2_2(LIST1, LIST2) RESULT(NSPEC2)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST1(:), LIST2(:)
  INTEGER(C_INT) :: NSPEC2
  INTEGER :: I
  NSPEC2 = 0
  NSPEC2 = MAX(NSPEC2, GET_NSPEC2_1(LIST1))
  NSPEC2 = MAX(NSPEC2, GET_NSPEC2_1(LIST2))
END FUNCTION

FUNCTION GET_NSPEC2_3(LIST1, LIST2, LIST3) RESULT(NSPEC2)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST1(:), LIST2(:), LIST3(:)
  INTEGER(C_INT) :: NSPEC2
