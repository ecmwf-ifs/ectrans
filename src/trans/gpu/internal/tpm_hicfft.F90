SUBROUTINE REPORT_FFT_PLAN_STATS(CDKIND,KFIELD)
  ! Print the device memory footprint of any FFT plans created by the preceding FFT call
  USE EC_PARKIND    ,ONLY : JPIM
  USE ISO_C_BINDING ,ONLY : C_INT, C_INT64_T
  USE TPM_GEN       ,ONLY : NOUT, NPRINTLEV

  IMPLICIT NONE

  CHARACTER(LEN=*),  INTENT(IN) :: CDKIND
  INTEGER(KIND=JPIM),INTENT(IN) :: KFIELD

#ifndef USE_ROCFFT
  INTEGER(KIND=C_INT) :: INEW_PLANS, INPLANS
  INTEGER(KIND=C_INT64_T) :: IWORKSPACE, IDEVICE_MEM, ITOTAL_WORKSPACE, ITOTAL_DEVICE_MEM

  ! Always query so that the "new plans" flag is cleared even when not printing
  CALL GET_FFT_PLAN_STATS(INEW_PLANS,INPLANS,IWORKSPACE,IDEVICE_MEM,ITOTAL_WORKSPACE,ITOTAL_DEVICE_MEM)

  IF (NPRINTLEV > 1 .AND. INEW_PLANS == 1) THEN
    WRITE(NOUT,'(A,A,A,I0,A,I0,A)') 'FFT plans created (', CDKIND, '): KFIELD=', KFIELD, &
      & ', NPLANS=', INPLANS, ' (one per latitude)'
    WRITE(NOUT,'(A)') '  this plan set:'
    WRITE(NOUT,'(A,F12.3,A)') '  work areas (sum of hipfftGetSize)         : ', &
      & REAL(IWORKSPACE)/1000.0**3, ' GB'
    WRITE(NOUT,'(A,F12.3,A)') '  device memory used (drop in free memory)  : ', &
      & REAL(IDEVICE_MEM)/1000.0**3, ' GB'
    WRITE(NOUT,'(A)') '  cumulative over all plan sets:'
    WRITE(NOUT,'(A,F12.3,A)') '  work areas                                : ', &
      & REAL(ITOTAL_WORKSPACE)/1000.0**3, ' GB'
    WRITE(NOUT,'(A,F12.3,A)') '  device memory used                        : ', &
      & REAL(ITOTAL_DEVICE_MEM)/1000.0**3, ' GB'
  ENDIF
#endif

END SUBROUTINE REPORT_FFT_PLAN_STATS


SUBROUTINE EXECUTE_DIR_FFT_FLOAT(PREEL_REAL,PREEL_COMPLEX,RESOL_ID,KFIELD,LOENS,OFFSETS,ALLOC)
  USE EC_PARKIND ,ONLY : JPIM, JPIB

  IMPLICIT NONE

  REAL(KIND=C_FLOAT), POINTER, INTENT(IN) :: PREEL_REAL(:)
  REAL(KIND=C_FLOAT), POINTER, INTENT(OUT) :: PREEL_COMPLEX(:)
  INTEGER(KIND=JPIM),INTENT(IN)  :: RESOL_ID
  INTEGER(KIND=JPIM),INTENT(IN)  :: KFIELD
  INTEGER(KIND=JPIM),INTENT(IN)  :: LOENS(:)
  INTEGER(KIND=JPIB),INTENT(IN)  :: OFFSETS(:)
  TYPE(GROWING_ALLOCATION_TYPE), INTENT(IN), POINTER :: ALLOC
  INTERFACE
#ifdef USE_ROCFFT
    SUBROUTINE EXECUTE_DIR_FFT_FLOAT_C(PREEL_REAL,PREEL_COMPLEX,RESOL_ID,KFIELD,LOENS,OFFSETS,NFFT,ALLOC) &
 &                   BIND(C, NAME="execute_dir_rocfft_float")
#else
    SUBROUTINE EXECUTE_DIR_FFT_FLOAT_C(PREEL_REAL,PREEL_COMPLEX,RESOL_ID,KFIELD,LOENS,OFFSETS,NFFT,ALLOC) &
 &                   BIND(C, NAME="execute_dir_fft_float")
#endif
      USE ISO_C_BINDING, ONLY: C_FLOAT, C_INT, C_PTR, C_INT64_T
      TYPE(C_PTR), VALUE :: PREEL_REAL
      TYPE(C_PTR), VALUE :: PREEL_COMPLEX
      INTEGER(KIND=C_INT),INTENT(IN),VALUE  :: RESOL_ID
      INTEGER(KIND=C_INT),INTENT(IN),VALUE  :: KFIELD
      INTEGER(KIND=C_INT),INTENT(IN)  :: LOENS(*)
      INTEGER(KIND=C_INT64_T),INTENT(IN)  :: OFFSETS(*)
      INTEGER(KIND=C_INT),INTENT(IN),VALUE :: NFFT
      TYPE(C_PTR), INTENT(IN), VALUE :: ALLOC
    END SUBROUTINE
  END INTERFACE

#ifdef ACCGPU
  !$ACC HOST_DATA USE_DEVICE(PREEL_REAL,PREEL_COMPLEX)
#endif
  CALL EXECUTE_DIR_FFT_FLOAT_C(C_LOC(PREEL_REAL),C_LOC(PREEL_COMPLEX),RESOL_ID,KFIELD,LOENS,OFFSETS,SIZE(LOENS),C_LOC(ALLOC))
#ifdef ACCGPU
  !$ACC END HOST_DATA
#endif

  CALL REPORT_FFT_PLAN_STATS('direct, single', KFIELD)

END SUBROUTINE EXECUTE_DIR_FFT_FLOAT
