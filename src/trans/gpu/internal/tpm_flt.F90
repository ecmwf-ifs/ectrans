CONTAINS

SUBROUTINE FLATTEN_BUTTERFLY_STRUCT(YD_FLT, CD_MODE, YD_BUT_FLAT)
! Convert the given butterfly struct (either antisymmetric (CD_MODE="ANTI") or symmetric
! (CD_MODE="SYMM")) into a flattened representation which can be easily copied to GPU.

TYPE(FLT_TYPE), INTENT(IN), TARGET :: YD_FLT(:)
CHARACTER(LEN=4), INTENT(IN) :: CD_MODE
TYPE(BUTTERFLY_STRUCT_FLAT), INTENT(OUT) :: YD_BUT_FLAT

INTEGER(KIND=JPIM) :: NUM_MODES
INTEGER(KIND=JPIM) :: I, J, I_TOTAL, I_TOTAL_NODES, I_TOTAL_ICLIST, I_TOTAL_PNONIM, I_TOTAL_B
INTEGER(KIND=JPIM) :: JJ, JK, JR, L, IDX, NBASE, IJ_L, ICOFF, IPOFF, IBOFF
TYPE(BUTTERFLY_STRUCT), POINTER :: YL_BUT_STRUCT

NUM_MODES = SIZE(YD_FLT)

ALLOCATE(YD_BUT_FLAT%N_ORDER(NUM_MODES))
ALLOCATE(YD_BUT_FLAT%N_LEVELS(NUM_MODES))
ALLOCATE(YD_BUT_FLAT%IBETALEN_MAX(NUM_MODES))
ALLOCATE(YD_BUT_FLAT%SLEV_OFFSET(NUM_MODES+1))

DO I = 1, NUM_MODES
  IF (CD_MODE == "ANTI") THEN
    YL_BUT_STRUCT => YD_FLT(I)%YBUT_STRUCT_A
  ELSE
    YL_BUT_STRUCT => YD_FLT(I)%YBUT_STRUCT_S
  ENDIF
  YD_BUT_FLAT%N_ORDER(I) = YL_BUT_STRUCT%N_ORDER
  YD_BUT_FLAT%N_LEVELS(I) = YL_BUT_STRUCT%N_LEVELS
  YD_BUT_FLAT%IBETALEN_MAX(I) = YL_BUT_STRUCT%IBETALEN_MAX
ENDDO

YD_BUT_FLAT%SLEV_OFFSET(1) = 0
DO I = 1, NUM_MODES
  YD_BUT_FLAT%SLEV_OFFSET(I+1) = YD_BUT_FLAT%SLEV_OFFSET(I) &
    & + YD_BUT_FLAT%N_LEVELS(I) + 1
ENDDO
I_TOTAL = YD_BUT_FLAT%SLEV_OFFSET(NUM_MODES+1)
ALLOCATE(YD_BUT_FLAT%SLEV_IJ(I_TOTAL))
ALLOCATE(YD_BUT_FLAT%SLEV_IK(I_TOTAL))
ALLOCATE(YD_BUT_FLAT%SLEV_IBETALEN(I_TOTAL))

DO I = 1, NUM_MODES
  IF (CD_MODE == "ANTI") THEN
    YL_BUT_STRUCT => YD_FLT(I)%YBUT_STRUCT_A
  ELSE
    YL_BUT_STRUCT => YD_FLT(I)%YBUT_STRUCT_S
  ENDIF
  DO J = 0, YL_BUT_STRUCT%N_LEVELS
    YD_BUT_FLAT%SLEV_IJ(YD_BUT_FLAT%SLEV_OFFSET(I)+J+1) = YL_BUT_STRUCT%SLEV(J)%IJ
    YD_BUT_FLAT%SLEV_IK(YD_BUT_FLAT%SLEV_OFFSET(I)+J+1) = YL_BUT_STRUCT%SLEV(J)%IK
    YD_BUT_FLAT%SLEV_IBETALEN(YD_BUT_FLAT%SLEV_OFFSET(I)+J+1) = YL_BUT_STRUCT%SLEV(J)%IBETALEN
  ENDDO
ENDDO

! Per-level node offsets: prefix sum over all level slots, IJ*IK nodes per slot
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_OFFSET(I_TOTAL+1))
YD_BUT_FLAT%SLEV_NODE_OFFSET(1) = 0
DO L = 1, I_TOTAL
  YD_BUT_FLAT%SLEV_NODE_OFFSET(L+1) = YD_BUT_FLAT%SLEV_NODE_OFFSET(L) &
    & + YD_BUT_FLAT%SLEV_IJ(L) * YD_BUT_FLAT%SLEV_IK(L)
ENDDO
I_TOTAL_NODES = YD_BUT_FLAT%SLEV_NODE_OFFSET(I_TOTAL+1)
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_IFCOL(I_TOTAL_NODES))
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_ILCOL(I_TOTAL_NODES))
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_IFROW(I_TOTAL_NODES))
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_ILROW(I_TOTAL_NODES))
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_ICOLS(I_TOTAL_NODES))
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_IROWS(I_TOTAL_NODES))
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_IRANK(I_TOTAL_NODES))
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_IOFFBETA(I_TOTAL_NODES))

DO I = 1, NUM_MODES
  IF (CD_MODE == "ANTI") THEN
    YL_BUT_STRUCT => YD_FLT(I)%YBUT_STRUCT_A
  ELSE
    YL_BUT_STRUCT => YD_FLT(I)%YBUT_STRUCT_S
  ENDIF
  DO J = 0, YL_BUT_STRUCT%N_LEVELS
    L = YD_BUT_FLAT%SLEV_OFFSET(I) + J + 1
    NBASE = YD_BUT_FLAT%SLEV_NODE_OFFSET(L)
    IJ_L = YL_BUT_STRUCT%SLEV(J)%IJ
    DO JK = 1, YL_BUT_STRUCT%SLEV(J)%IK
      DO JJ = 1, IJ_L
        ! Column-major linearisation of NODE(JJ,JK), matching Fortran storage
        IDX = NBASE + (JK-1)*IJ_L + JJ
        ASSOCIATE(YN => YL_BUT_STRUCT%SLEV(J)%NODE(JJ,JK))
        YD_BUT_FLAT%SLEV_NODE_IFCOL(IDX)    = YN%IFCOL
        YD_BUT_FLAT%SLEV_NODE_ILCOL(IDX)    = YN%ILCOL
        YD_BUT_FLAT%SLEV_NODE_IFROW(IDX)    = YN%IFROW
        YD_BUT_FLAT%SLEV_NODE_ILROW(IDX)    = YN%ILROW
        YD_BUT_FLAT%SLEV_NODE_ICOLS(IDX)    = YN%ICOLS
        YD_BUT_FLAT%SLEV_NODE_IROWS(IDX)    = YN%IROWS
        YD_BUT_FLAT%SLEV_NODE_IRANK(IDX)    = YN%IRANK
        YD_BUT_FLAT%SLEV_NODE_IOFFBETA(IDX) = YN%IOFFBETA
        END ASSOCIATE
      ENDDO
    ENDDO
  ENDDO
ENDDO

! Per-node ICLIST offsets: prefix sum over all nodes, ICOLS entries per node
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_ICLIST_OFFSET(I_TOTAL_NODES+1))
YD_BUT_FLAT%SLEV_NODE_ICLIST_OFFSET(1) = 0
DO IDX = 1, I_TOTAL_NODES
  YD_BUT_FLAT%SLEV_NODE_ICLIST_OFFSET(IDX+1) = YD_BUT_FLAT%SLEV_NODE_ICLIST_OFFSET(IDX) &
    & + YD_BUT_FLAT%SLEV_NODE_ICOLS(IDX)
ENDDO
I_TOTAL_ICLIST = YD_BUT_FLAT%SLEV_NODE_ICLIST_OFFSET(I_TOTAL_NODES+1)
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_ICLIST(I_TOTAL_ICLIST))

! Per-node PNONIM and B offsets. PNONIM holds IRANK*(ICOLS-IRANK) entries per node; B holds
! IROWS*IRANK, but is only present on the last level of each mode, so every other node gets a
! zero-length slot. Both stay column-major as in NODE_TYPE, so their shapes are recoverable
! from SLEV_NODE_IRANK/ICOLS/IROWS and they can still be passed to GEMM directly. Unlike ICLIST
! these lengths are not a simple function of one existing flat array, so they are gathered one
! slot up and then turned into a prefix sum in place.
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_PNONIM_OFFSET(I_TOTAL_NODES+1))
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_B_OFFSET(I_TOTAL_NODES+1))
YD_BUT_FLAT%SLEV_NODE_PNONIM_OFFSET(:) = 0
YD_BUT_FLAT%SLEV_NODE_B_OFFSET(:) = 0

DO I = 1, NUM_MODES
  IF (CD_MODE == "ANTI") THEN
    YL_BUT_STRUCT => YD_FLT(I)%YBUT_STRUCT_A
  ELSE
    YL_BUT_STRUCT => YD_FLT(I)%YBUT_STRUCT_S
  ENDIF
  DO J = 0, YL_BUT_STRUCT%N_LEVELS
    L = YD_BUT_FLAT%SLEV_OFFSET(I) + J + 1
    NBASE = YD_BUT_FLAT%SLEV_NODE_OFFSET(L)
    IJ_L = YL_BUT_STRUCT%SLEV(J)%IJ
    DO JK = 1, YL_BUT_STRUCT%SLEV(J)%IK
      DO JJ = 1, IJ_L
        IDX = NBASE + (JK-1)*IJ_L + JJ
        ASSOCIATE(YN => YL_BUT_STRUCT%SLEV(J)%NODE(JJ,JK))
        IF (YN%IRANK*(YN%ICOLS-YN%IRANK) > 0) THEN
          IF (.NOT. ASSOCIATED(YN%PNONIM)) THEN
            CALL ABORT_TRANS('FLATTEN_BUTTERFLY_STRUCT: PNONIM NOT ASSOCIATED')
          ENDIF
          IF (SIZE(YN%PNONIM) /= YN%IRANK*(YN%ICOLS-YN%IRANK)) THEN
            CALL ABORT_TRANS('FLATTEN_BUTTERFLY_STRUCT: SIZE(PNONIM) /= IRANK*(ICOLS-IRANK)')
          ENDIF
          YD_BUT_FLAT%SLEV_NODE_PNONIM_OFFSET(IDX+1) = YN%IRANK*(YN%ICOLS-YN%IRANK)
        ENDIF
        IF (ASSOCIATED(YN%B)) THEN
          IF (SIZE(YN%B,DIM=1) /= YN%IROWS .OR. SIZE(YN%B,DIM=2) /= YN%IRANK) THEN
            CALL ABORT_TRANS('FLATTEN_BUTTERFLY_STRUCT: SHAPE(B) /= (IROWS,IRANK)')
          ENDIF
          YD_BUT_FLAT%SLEV_NODE_B_OFFSET(IDX+1) = YN%IROWS*YN%IRANK
        ENDIF
        END ASSOCIATE
      ENDDO
    ENDDO
  ENDDO
ENDDO

DO IDX = 1, I_TOTAL_NODES
  YD_BUT_FLAT%SLEV_NODE_PNONIM_OFFSET(IDX+1) = YD_BUT_FLAT%SLEV_NODE_PNONIM_OFFSET(IDX+1) &
    & + YD_BUT_FLAT%SLEV_NODE_PNONIM_OFFSET(IDX)
  YD_BUT_FLAT%SLEV_NODE_B_OFFSET(IDX+1) = YD_BUT_FLAT%SLEV_NODE_B_OFFSET(IDX+1) &
    & + YD_BUT_FLAT%SLEV_NODE_B_OFFSET(IDX)
ENDDO
I_TOTAL_PNONIM = YD_BUT_FLAT%SLEV_NODE_PNONIM_OFFSET(I_TOTAL_NODES+1)
I_TOTAL_B = YD_BUT_FLAT%SLEV_NODE_B_OFFSET(I_TOTAL_NODES+1)
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_PNONIM(I_TOTAL_PNONIM))
ALLOCATE(YD_BUT_FLAT%SLEV_NODE_B(I_TOTAL_B))

DO I = 1, NUM_MODES
  IF (CD_MODE == "ANTI") THEN
    YL_BUT_STRUCT => YD_FLT(I)%YBUT_STRUCT_A
  ELSE
    YL_BUT_STRUCT => YD_FLT(I)%YBUT_STRUCT_S
  ENDIF
  DO J = 0, YL_BUT_STRUCT%N_LEVELS
    L = YD_BUT_FLAT%SLEV_OFFSET(I) + J + 1
    NBASE = YD_BUT_FLAT%SLEV_NODE_OFFSET(L)
    IJ_L = YL_BUT_STRUCT%SLEV(J)%IJ
    DO JK = 1, YL_BUT_STRUCT%SLEV(J)%IK
      DO JJ = 1, IJ_L
        IDX = NBASE + (JK-1)*IJ_L + JJ
        ASSOCIATE(YN => YL_BUT_STRUCT%SLEV(J)%NODE(JJ,JK))
        ICOFF = YD_BUT_FLAT%SLEV_NODE_ICLIST_OFFSET(IDX)
        IF (YN%ICOLS > 0) THEN
          IF (.NOT. ASSOCIATED(YN%ICLIST)) THEN
            CALL ABORT_TRANS('FLATTEN_BUTTERFLY_STRUCT: ICLIST NOT ASSOCIATED')
          ENDIF
          IF (SIZE(YN%ICLIST) /= YN%ICOLS) THEN
            CALL ABORT_TRANS('FLATTEN_BUTTERFLY_STRUCT: SIZE(ICLIST) /= ICOLS')
          ENDIF
          YD_BUT_FLAT%SLEV_NODE_ICLIST(ICOFF+1:ICOFF+YN%ICOLS) = YN%ICLIST(1:YN%ICOLS)
        ENDIF
        IPOFF = YD_BUT_FLAT%SLEV_NODE_PNONIM_OFFSET(IDX)
        IF (YN%IRANK*(YN%ICOLS-YN%IRANK) > 0) THEN
          YD_BUT_FLAT%SLEV_NODE_PNONIM(IPOFF+1:IPOFF+YN%IRANK*(YN%ICOLS-YN%IRANK)) = YN%PNONIM(:)
        ENDIF
        IBOFF = YD_BUT_FLAT%SLEV_NODE_B_OFFSET(IDX)
        IF (ASSOCIATED(YN%B)) THEN
          ! Column-major flattening of B(IROWS,IRANK), matching Fortran storage
          DO JR = 1, YN%IRANK
            YD_BUT_FLAT%SLEV_NODE_B(IBOFF+(JR-1)*YN%IROWS+1:IBOFF+JR*YN%IROWS) = &
              & YN%B(1:YN%IROWS,JR)
          ENDDO
        ENDIF
        END ASSOCIATE
      ENDDO
    ENDDO
  ENDDO
ENDDO

END SUBROUTINE FLATTEN_BUTTERFLY_STRUCT

END MODULE TPM_FLT
