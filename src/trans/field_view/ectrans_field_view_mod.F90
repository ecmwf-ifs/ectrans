SUBROUTINE FIELD_VIEW_SET_IVSET_PTR(YLFV, IVSET, IVSET_BASE)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  INTEGER(KIND=C_INT), TARGET, OPTIONAL, INTENT(IN) :: IVSET(:)
  INTEGER(KIND=C_INT), OPTIONAL, INTENT(IN) :: IVSET_BASE
  YLFV%IVSET_BASE = 1
  IF (PRESENT(IVSET_BASE)) YLFV%IVSET_BASE = IVSET_BASE
  IF (PRESENT(IVSET)) THEN
    IF (SIZE(IVSET) > 0) THEN
      YLFV%IVSET = C_LOC(IVSET(1))
      YLFV%IVSET_SIZE = SIZE(IVSET)
      RETURN
    ENDIF
  ENDIF
  YLFV%IVSET = C_NULL_PTR
  YLFV%IVSET_SIZE = 0
END SUBROUTINE

SUBROUTINE FIELD_VIEW_GET_IVSET_PTR(YLFV, IVSET)
  TYPE(FIELD_VIEW), INTENT(IN) :: YLFV
  INTEGER(KIND=C_INT), POINTER, INTENT(INOUT) :: IVSET(:)
  IF (YLFV%IVSET_SIZE == 0) THEN
    NULLIFY(IVSET)
  ELSE
    CALL C_F_POINTER(YLFV%IVSET, IVSET, [YLFV%IVSET_SIZE])
  ENDIF
END SUBROUTINE

