PURE FUNCTION FIELD_VIEW_GET_EXTENT(YLFV, FORTRAN_DIM) RESULT(EXTENT)
  TYPE(FIELD_VIEW), INTENT(IN) :: YLFV
  INTEGER, INTENT(IN) :: FORTRAN_DIM
  INTEGER(C_INT) :: EXTENT
  EXTENT = YLFV%EXTENTS(YLFV%RANK-FORTRAN_DIM+1)
END FUNCTION

PURE FUNCTION FIELD_VIEW_GET_STRIDE(YLFV, FORTRAN_DIM) RESULT(STRIDE)
  TYPE(FIELD_VIEW), INTENT(IN) :: YLFV
  INTEGER, INTENT(IN) :: FORTRAN_DIM
  INTEGER(C_INT) :: STRIDE
  STRIDE = YLFV%STRIDES(YLFV%RANK-FORTRAN_DIM+1)
END FUNCTION

PURE FUNCTION FIELD_VIEW_GET_DIM_ROLE(YLFV, FORTRAN_DIM) RESULT(ROLE)
  TYPE(FIELD_VIEW), INTENT(IN) :: YLFV
  INTEGER, INTENT(IN) :: FORTRAN_DIM
  INTEGER(C_INT) :: ROLE
  INTEGER(C_INT) :: C_DIM
  INTEGER(C_INT), PARAMETER :: DIM_ROLE_MASK = INT(Z'F', C_INT)
  C_DIM = YLFV%RANK-FORTRAN_DIM+1
  ROLE = IAND(ISHFT(YLFV%INDEXING, -DIM_ROLE_BITS * (C_DIM - 1)), DIM_ROLE_MASK)
END FUNCTION

PURE FUNCTION FIELD_VIEW_GET_EXTENT_BY_ROLE(YLFV, DIM_ROLE) RESULT(EXTENT)
  TYPE(FIELD_VIEW), INTENT(IN) :: YLFV
  INTEGER, INTENT(IN) :: DIM_ROLE
  INTEGER(C_INT) :: EXTENT
  INTEGER :: FORTRAN_DIM
  EXTENT = 0
  DO FORTRAN_DIM = 1, YLFV%RANK
    IF (FIELD_VIEW_GET_DIM_ROLE(YLFV, FORTRAN_DIM) == DIM_ROLE) THEN
      EXTENT = FIELD_VIEW_GET_EXTENT(YLFV, FORTRAN_DIM)
      RETURN
    ENDIF
  ENDDO
END FUNCTION

PURE SUBROUTINE FIELD_VIEW_SET_IVSET_DIM(YLFV, FORTRAN_DIM)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  INTEGER, INTENT(IN) :: FORTRAN_DIM
  IF (FORTRAN_DIM == 0) THEN
    YLFV%IVSET_DIM = -1
  ELSE
    YLFV%IVSET_DIM = YLFV%RANK-FORTRAN_DIM
  ENDIF
END SUBROUTINE

PURE SUBROUTINE FIELD_VIEW_GET_IVSET_DIM(YLFV, FORTRAN_DIM)
  TYPE(FIELD_VIEW), INTENT(IN) :: YLFV
  INTEGER, INTENT(OUT) :: FORTRAN_DIM
  IF (YLFV%IVSET_DIM < 0) THEN
    FORTRAN_DIM = 0
  ELSE
    FORTRAN_DIM = YLFV%RANK-YLFV%IVSET_DIM
  ENDIF
END SUBROUTINE

SUBROUTINE FIELD_VIEW_SET_NAME(YLFV, NAME)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  CHARACTER(LEN=*), TARGET, INTENT(IN) :: NAME
