TYPE :: FIELD_VIEW_DIM_ROLE_TYPE
  INTEGER(C_INT) :: UNKNOWN = DIM_UNKNOWN
  INTEGER(C_INT) :: NPROMA  = DIM_NPROMA
  INTEGER(C_INT) :: BLOCK   = DIM_BLOCK
  INTEGER(C_INT) :: LEVEL   = DIM_LEVEL
  INTEGER(C_INT) :: FIELD   = DIM_FIELD
  INTEGER(C_INT) :: SPEC2   = DIM_SPEC2
END TYPE FIELD_VIEW_DIM_ROLE_TYPE

TYPE(FIELD_VIEW_DIM_ROLE_TYPE), SAVE, PROTECTED :: FIELD_VIEW_DIM_ROLE

INTEGER, PARAMETER :: DIM_ROLE_BITS = 4

! INDEXING uses C dimension ordering. The least-significant role describes EXTENTS(1).
! C array shapes represented by the indexing values.
INTEGER(C_INT), PARAMETER :: &
  & INDEXING_UNKNOWN                    = DIM_UNKNOWN, &
  & C_INDEXING_BLOCK                    = DIM_BLOCK,                                          & ! array[NBLKS]
  & C_INDEXING_BLOCK_NPROMA             = IOR(DIM_BLOCK, ISHFT(DIM_NPROMA, DIM_ROLE_BITS)),   & ! array[NBLKS][NPROMA]
  & C_INDEXING_BLOCK_LEVEL_NPROMA       = IOR(DIM_BLOCK, IOR(ISHFT(DIM_LEVEL, DIM_ROLE_BITS), & ! array[NBLKS][NLEVS][NPROMA]
                                        & ISHFT(DIM_NPROMA, 2 * DIM_ROLE_BITS))),             &
  & C_INDEXING_BLOCK_FIELD_LEVEL_NPROMA = IOR(DIM_BLOCK, IOR(ISHFT(DIM_FIELD, DIM_ROLE_BITS), & ! array[NBLKS][NFIELDS][NLEVS][NPROMA]
                                        & IOR(ISHFT(DIM_LEVEL, 2 * DIM_ROLE_BITS),            &
                                        & ISHFT(DIM_NPROMA, 3 * DIM_ROLE_BITS)))),            &
  & C_INDEXING_SPEC2                    = DIM_SPEC2,                                          & ! array[NSPEC2]
  & C_INDEXING_SPEC2_LEVEL              = IOR(DIM_SPEC2, ISHFT(DIM_LEVEL, DIM_ROLE_BITS)),    & ! array[NSPEC2][NLEVS]
  & C_INDEXING_FIELD_SPEC2_LEVEL        = IOR(DIM_FIELD, IOR(ISHFT(DIM_SPEC2, DIM_ROLE_BITS), & ! array[NFIELDS][NSPEC2][NLEVS]
                                        & ISHFT(DIM_LEVEL, 2 * DIM_ROLE_BITS)))

! Fortran array shapes represented by the C-ordered indexing values.
TYPE :: FIELD_VIEW_INDEXING_TYPE
  INTEGER(C_INT) :: UNKNOWN                  = INDEXING_UNKNOWN
  INTEGER(C_INT) :: BLOCK                    = C_INDEXING_BLOCK                    ! ARRAY(NBLKS)
  INTEGER(C_INT) :: NPROMA_BLOCK             = C_INDEXING_BLOCK_NPROMA             ! ARRAY(NPROMA, NBLKS)
  INTEGER(C_INT) :: NPROMA_LEVEL_BLOCK       = C_INDEXING_BLOCK_LEVEL_NPROMA       ! ARRAY(NPROMA, NLEVS, NBLKS)
  INTEGER(C_INT) :: NPROMA_LEVEL_FIELD_BLOCK = C_INDEXING_BLOCK_FIELD_LEVEL_NPROMA ! ARRAY(NPROMA, NLEVS, NFIELDS, NBLKS)
  INTEGER(C_INT) :: SPEC2                    = C_INDEXING_SPEC2                    ! ARRAY(NSPEC2)
  INTEGER(C_INT) :: LEVEL_SPEC2              = C_INDEXING_SPEC2_LEVEL              ! ARRAY(NLEVS, NSPEC2)
  INTEGER(C_INT) :: LEVEL_SPEC2_FIELD        = C_INDEXING_FIELD_SPEC2_LEVEL        ! ARRAY(NLEVS, NSPEC2, NFIELDS)
END TYPE FIELD_VIEW_INDEXING_TYPE

TYPE(FIELD_VIEW_INDEXING_TYPE), SAVE, PROTECTED :: FIELD_VIEW_INDEXING

! C-interoperable view of field data and its shape, stride, and dimension-role metadata.
! Array metadata uses C dimension ordering. Spectral fields may additionally reference
! an IVSET array assigning each level to a spectral distribution set.
TYPE, BIND(C) :: FIELD_VIEW

  ! ARRAY
  TYPE(C_PTR)    :: DATA
  INTEGER(C_INT) :: ACCESS
  INTEGER(C_INT) :: KIND
  INTEGER(C_INT) :: RANK
  INTEGER(C_INT) :: EXTENTS(MAX_RANK) ! C ORDERING
  INTEGER(C_INT) :: STRIDES(MAX_RANK) ! C ORDERING

  ! IVSET
  TYPE(C_PTR)    :: IVSET ! Value indexing is specified by IVSET_BASE
  INTEGER(C_INT) :: IVSET_SIZE
  INTEGER(C_INT) :: IVSET_DIM ! C ORDERING; -1 when IVSET does not index distribution array dimension
  INTEGER(C_INT) :: IVSET_BASE ! 0 for zero-based values, 1 for one-based values

  ! NAME
  TYPE(C_PTR)    :: NAME
  INTEGER(C_INT) :: NAME_SIZE

  ! INDEXING
  INTEGER(C_INT) :: INDEXING ! NOTE: C ORDERING

END TYPE

INTERFACE FIELD_VIEW_GET_DATA_PTR
