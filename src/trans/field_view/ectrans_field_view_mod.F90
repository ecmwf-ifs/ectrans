SUBROUTINE SET_DATA_PTR_METADATA(YLFV, DATA, KIND, RANK, FORTRAN_EXTENTS, FORTRAN_OFFSETS)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  TYPE(C_PTR), INTENT(IN) :: DATA
  INTEGER(C_INT), INTENT(IN) :: KIND ! bytes of data type (e.g., 4 for REAL(C_FLOAT), 8 for REAL(C_DOUBLE))
  INTEGER(C_INT), INTENT(IN) :: RANK
  INTEGER(C_INT), INTENT(IN) :: FORTRAN_EXTENTS(RANK)
  INTEGER(C_INTPTR_T), INTENT(IN) :: FORTRAN_OFFSETS(RANK)
  INTEGER(C_INT) :: FORTRAN_STRIDES(RANK)
  INTEGER :: JDIM, JFIRST

  YLFV%DATA = DATA
  YLFV%KIND = KIND
  YLFV%RANK = RANK
  YLFV%EXTENTS = 0
  YLFV%STRIDES = 0

  IF (PRODUCT(FORTRAN_EXTENTS) == 1) THEN
    FORTRAN_STRIDES = 1
  ELSE
    FORTRAN_STRIDES = 0
    JFIRST = 0
    DO JDIM = 1, RANK
      IF (FORTRAN_OFFSETS(JDIM) /= 0) THEN
        JFIRST = JDIM
        EXIT
      ENDIF
    ENDDO
    IF (JFIRST > 0) FORTRAN_STRIDES(1) = FORTRAN_OFFSETS(JFIRST) / KIND
    DO JDIM = 2, RANK
      IF (FORTRAN_OFFSETS(JDIM) /= 0) THEN
        FORTRAN_STRIDES(JDIM) = FORTRAN_OFFSETS(JDIM) / KIND
      ELSE
        FORTRAN_STRIDES(JDIM) = FORTRAN_STRIDES(JDIM-1) * FORTRAN_EXTENTS(JDIM-1)
      ENDIF
    ENDDO
  ENDIF

  DO JDIM = 1, RANK
    YLFV%EXTENTS(RANK-JDIM+1) = FORTRAN_EXTENTS(JDIM)
    YLFV%STRIDES(RANK-JDIM+1) = FORTRAN_STRIDES(JDIM)
  ENDDO
END SUBROUTINE

SUBROUTINE SET_DATA_PTR_1RM(YLFV, PTR)
  TYPE(FIELD_VIEW), INTENT(INOUT) :: YLFV
  REAL(C_FLOAT), POINTER, INTENT(IN) :: PTR(:)
  INTEGER(C_INT), PARAMETER :: RANK = 1
  INTEGER(C_INT) :: EXTENTS(RANK)
  INTEGER(C_INTPTR_T) :: BASE, OFFSETS(RANK)
  TYPE(C_PTR) :: DATA
  DATA = C_LOC(PTR(1))
  BASE = TRANSFER(DATA, BASE)
  EXTENTS = SHAPE(PTR)
  OFFSETS = 0
  IF (SIZE(PTR, 1) > 1) OFFSETS(1) = TRANSFER(C_LOC(PTR(2)), BASE) - BASE
  CALL SET_DATA_PTR_METADATA(YLFV, DATA, STORAGE_SIZE(PTR)/8, RANK, EXTENTS, OFFSETS)
END SUBROUTINE

