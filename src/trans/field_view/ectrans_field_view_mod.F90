  CALL ASSERT_EXPECTED_RANK_AND_KIND("GET_DATA_PTR_1RM", YLFV, RANK, C_FLOAT)
  IF (FIELD_VIEW_GET_STRIDE(YLFV, 1) == 1) THEN
    CALL C_F_POINTER(YLFV%DATA, PTR, [FIELD_VIEW_GET_EXTENT(YLFV, 1)])
  ELSE
    BLOCK
      REAL(C_FLOAT), POINTER :: BACKING(:,:)
      INTEGER(C_INT) :: EXTENTS(RANK+1)
      EXTENTS(1) = FIELD_VIEW_GET_STRIDE(YLFV, 1)
      EXTENTS(2) = FIELD_VIEW_GET_EXTENT(YLFV, 1)
      CALL C_F_POINTER(YLFV%DATA, BACKING, EXTENTS)
      PTR => BACKING(1, 1:FIELD_VIEW_GET_EXTENT(YLFV, 1))
    END BLOCK
  ENDIF
END SUBROUTINE

