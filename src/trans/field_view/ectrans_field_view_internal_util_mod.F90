SUBROUTINE ASSERT_DIM_ROLE(YLF, FORTRAN_DIM, EXPECTED_ROLE, ROUTINE)
  TYPE(FIELD_VIEW), INTENT(IN) :: YLF
  INTEGER, INTENT(IN) :: FORTRAN_DIM, EXPECTED_ROLE
  CHARACTER(LEN=*), INTENT(IN) :: ROUTINE
  IF (FIELD_VIEW_GET_DIM_ROLE(YLF, FORTRAN_DIM) /= EXPECTED_ROLE) THEN
    CALL ABORT_TRANS(ROUTINE // " FAILURE: FIELD_VIEW DIMENSION ROLE MISMATCH")
  ENDIF
END SUBROUTINE

SUBROUTINE ASSERT_IVSET_LEVEL(YLF, ROUTINE)
  TYPE(FIELD_VIEW), INTENT(IN) :: YLF
  CHARACTER(LEN=*), INTENT(IN) :: ROUTINE
  INTEGER :: IVSET_DIM
  CALL FIELD_VIEW_GET_IVSET_DIM(YLF, IVSET_DIM)
  IF (IVSET_DIM > 0) CALL ASSERT_DIM_ROLE(YLF, IVSET_DIM, FIELD_VIEW_DIM_ROLE%LEVEL, ROUTINE)
END SUBROUTINE

SUBROUTINE PROCESS_NPROMA(LIST, NPROMA)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST(:)
  INTEGER(JPIM), INTENT(INOUT) :: NPROMA
  INTEGER :: I
  INTEGER(JPIM) :: FIELD_NPROMA
  DO I = 1, SIZE(LIST)
    FIELD_NPROMA = FIELD_VIEW_GET_EXTENT_BY_ROLE(LIST(I), FIELD_VIEW_DIM_ROLE%NPROMA)
    IF (FIELD_NPROMA == 0) FIELD_NPROMA = 1
    IF (NPROMA == 0) THEN
      NPROMA = FIELD_NPROMA
    ELSE IF (NPROMA /= FIELD_NPROMA) THEN
      CALL ABORT_TRANS("GET_NPROMA FAILURE: Inconsistent NPROMA values across fields")
    ENDIF
  ENDDO
END SUBROUTINE

FUNCTION GET_NPROMA_1(LIST) RESULT(NPROMA)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST(:)
  INTEGER(JPIM) :: NPROMA
  NPROMA = 0
  CALL PROCESS_NPROMA(LIST, NPROMA)
END FUNCTION

