SUBROUTINE PROCESS_NFLD(LIST, NFLD)
  TYPE(FIELD_VIEW), INTENT(IN) :: LIST(:)
  INTEGER(JPIM), INTENT(INOUT) :: NFLD
  INTEGER :: I
  INTEGER(JPIM) :: FIELD_NLEV, FIELD_NFLD
  DO I = 1, SIZE(LIST)
    FIELD_NLEV = MAX(FIELD_VIEW_GET_EXTENT_BY_ROLE(LIST(I), FIELD_VIEW_DIM_ROLE%LEVEL), 1)
    FIELD_NFLD = MAX(FIELD_VIEW_GET_EXTENT_BY_ROLE(LIST(I), FIELD_VIEW_DIM_ROLE%FIELD), 1)
    NFLD = NFLD + FIELD_NLEV * FIELD_NFLD
  ENDDO
END SUBROUTINE

