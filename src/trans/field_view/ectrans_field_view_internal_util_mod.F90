END SUBROUTINE LS1RB

SUBROUTINE LS2RB(LS2RBV,YLF)
  ! Creation of a list of SPEC_VIEW, each of them encapsulating a layer of an input FIELD_VIEW field.
  ! Given YLF dimensioned(NLEVS, NSPEC) as input,
  ! the output list size will contain (NLEVS) elements dimensioned(NSPEC)
  TYPE (FIELD_VIEW), POINTER, INTENT (IN) :: YLF
  TYPE (SPEC_VIEW), INTENT(INOUT) :: LS2RBV (:)

  REAL(KIND=JPRB), POINTER :: ZZ2 (:,:)
  CHARACTER(LEN=:), POINTER :: CNAME

  INTEGER(KIND=JPIM) :: JLEV, JCOUNT

  CALL ASSERT_DIM_ROLE(YLF, 1, FIELD_VIEW_DIM_ROLE%LEVEL, "LS2RB")
  CALL ASSERT_DIM_ROLE(YLF, 2, FIELD_VIEW_DIM_ROLE%SPEC2, "LS2RB")
  CALL ASSERT_IVSET_LEVEL(YLF, "LS2RB")
  CALL FIELD_VIEW_GET_DATA_PTR(YLF, ZZ2)
  CALL FIELD_VIEW_GET_NAME_PTR(YLF,CNAME)

  IF (SIZE(LS2RBV) /= SIZE (ZZ2, 1) ) CALL ABORT_TRANS("Error - incorrect size for LS2RBV")
  JCOUNT = 1

  DO JLEV = LBOUND (ZZ2, 1), UBOUND (ZZ2, 1)
    LS2RBV(JCOUNT)%P => ZZ2 (JLEV, :)
    LS2RBV(JCOUNT)%NAME => CNAME
    JCOUNT = JCOUNT + 1
  ENDDO
END SUBROUTINE LS2RB

SUBROUTINE LS3RB(LS3RBV,YLF)
  ! Creation of a list of SPEC_VIEW, each of them encapsulating a layer of an input FIELD_VIEW field.
  ! Given YLF dimensioned(NLEVS, NSPEC, NFIELDS) as input,
  ! the output list size will contain (NLEVS*NFIELDS) SPEC_VIEW, each of them dimensioned(NSPEC)
  TYPE (FIELD_VIEW), POINTER, INTENT (IN) :: YLF
  TYPE (SPEC_VIEW), INTENT(INOUT) :: LS3RBV (:)

  REAL(KIND=JPRB), POINTER :: ZZ3 (:,:,:)
  CHARACTER(LEN=:), POINTER :: CNAME

  INTEGER(KIND=JPIM) :: JLEV, JFLD, JCOUNT

  CALL ASSERT_DIM_ROLE(YLF, 1, FIELD_VIEW_DIM_ROLE%LEVEL, "LS3RB")
  CALL ASSERT_DIM_ROLE(YLF, 2, FIELD_VIEW_DIM_ROLE%SPEC2, "LS3RB")
  CALL ASSERT_DIM_ROLE(YLF, 3, FIELD_VIEW_DIM_ROLE%FIELD, "LS3RB")
  CALL ASSERT_IVSET_LEVEL(YLF, "LS3RB")
  CALL FIELD_VIEW_GET_DATA_PTR(YLF, ZZ3)
  CALL FIELD_VIEW_GET_NAME_PTR(YLF,CNAME)

  IF (SIZE(LS3RBV) /=SIZE (ZZ3, 1) * SIZE (ZZ3, 3) ) CALL ABORT_TRANS("Error - incorrect size for LS3RBV")

  JCOUNT = 1
  DO JFLD = LBOUND (ZZ3, 3), UBOUND (ZZ3, 3)
    DO JLEV = LBOUND (ZZ3, 1), UBOUND (ZZ3, 1)
      LS3RBV(JCOUNT)%P => ZZ3 (JLEV, :, JFLD)
      LS3RBV(JCOUNT)%NAME => CNAME
      JCOUNT = JCOUNT + 1
    ENDDO
  ENDDO
END SUBROUTINE LS3RB

SUBROUTINE LS(YLFL,LSV)
! Creation of a list of SPEC_VIEW from a list YLFL of FIELD_BASIC_PTR
TYPE (FIELD_VIEW), TARGET, INTENT(IN) :: YLFL (:) ! input list of FIELD_BASIC_PTR
TYPE (SPEC_VIEW), INTENT(INOUT) :: LSV (:)        ! output list of SPEC_VIEW
INTEGER(KIND=JPIM) :: IOFF

INTEGER(KIND=JPIM) :: ILEN, JFLD

TYPE (FIELD_VIEW), POINTER:: YLF
REAL(KIND=JPRB), POINTER :: ZZ1 (:)

IOFF = 0
ILEN = -1

! iterate over YLFL LIST
DO JFLD = 1, SIZE (YLFL)
  ! compute number of SPEC_VIEW that will be generated for each field of the list
  ! in addition when LSV_PROVIDED: call the correct routine to create the SPEC_VIEW for each field of the list
  YLF => YLFL (JFLD)
  SELECT CASE (YLF%RANK)
    CASE (1)
      ILEN = 1
      CALL LS1RB(LSV(IOFF+1:IOFF+ILEN),YLF)
    CASE (2)
      ! Shape (NLEVS, NSPEC) -> NLEVS SPEC_VIEW of size NSPEC
      ILEN = FIELD_VIEW_GET_EXTENT(YLF, 1)
      CALL LS2RB(LSV(IOFF+1:IOFF+ILEN),YLF)
    CASE (3)
      ! Shape (NLEVS, NSPEC, NFIELDS) -> NLEVS*NFIELDS SPEC_VIEW of size NSPEC
      ILEN = FIELD_VIEW_GET_EXTENT(YLF, 1) * FIELD_VIEW_GET_EXTENT(YLF, 3)
      CALL LS3RB(LSV(IOFF+1:IOFF+ILEN),YLF)
    CASE (4)
      CALL ABORT_TRANS("LS not implemeted for RANK 4")
    CASE DEFAULT
      ! Skip the spectral field as it is not present on this processor
      ILEN = 1
  END SELECT

  IOFF = IOFF + ILEN
ENDDO

IF (SIZE(LSV) /= IOFF)  CALL ABORT_TRANS("LS FAILURE: LSV has incorrect size")

END SUBROUTINE LS

