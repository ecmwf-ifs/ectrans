FUNCTION LG_COUNT(YLFL) RESULT(IOFF)
  ! Compute the number of GRID_VIEW that will be generated for a list YLFL of FIELD_VIEW
  TYPE (FIELD_VIEW),TARGET, INTENT(IN) :: YLFL (:)      ! input list of FIELD_VIEW
  INTEGER(KIND=JPIM) :: IOFF
  INTEGER(KIND=JPIM) :: ILEN, JFLD

  IOFF = 0

  DO JFLD = 1, SIZE (YLFL)
    SELECT CASE (YLFL(JFLD)%RANK)
      CASE (1)
        ILEN = 1
      CASE (2)
        ILEN = 1
      CASE(3)
        ILEN = FIELD_VIEW_GET_EXTENT(YLFL(JFLD), 2)
      CASE(4)
        ILEN = FIELD_VIEW_GET_EXTENT(YLFL(JFLD), 2) * FIELD_VIEW_GET_EXTENT(YLFL(JFLD), 3)
      CASE DEFAULT
        CALL ABORT_TRANS("LG FAILURE: CLASS UNKNOWN")
    END SELECT
    IOFF = IOFF + ILEN
  ENDDO
END FUNCTION LG_COUNT

FUNCTION LS_COUNT(YLFL) RESULT(IOFF)
  ! Compute the number of SPEC_VIEW that will be generated for a list YLFL of FIELD_VIEW
  TYPE (FIELD_VIEW), TARGET, INTENT(IN) :: YLFL (:) ! input list of FIELD_VIEW
  INTEGER(KIND=JPIM) :: IOFF

  INTEGER(KIND=JPIM) :: ILEN, JFLD

  IOFF = 0

  DO JFLD = 1, SIZE (YLFL)
    SELECT CASE (YLFL(JFLD)%RANK)
      CASE (1)
        ILEN = 1
      CASE (2)
        ! Shape (NLEVS, NSPEC) -> NLEVS SPEC_VIEW of size NSPEC
        ILEN = FIELD_VIEW_GET_EXTENT(YLFL(JFLD), 1)
      CASE (3)
        ! Shape (NLEVS, NSPEC, NFIELDS) -> NLEVS*NFIELDS SPEC_VIEW of size NSPEC
        ILEN = FIELD_VIEW_GET_EXTENT(YLFL(JFLD), 1) * FIELD_VIEW_GET_EXTENT(YLFL(JFLD), 3)
      CASE (4)
        CALL ABORT_TRANS("LS not implemeted for RANK 4")
      CASE DEFAULT
        ! Skip the spectral field as it is not present on this processor
        ILEN = 1
    END SELECT
    IOFF = IOFF + ILEN
  ENDDO

END FUNCTION LS_COUNT

SUBROUTINE LG2RB(LG2RBV,YLF,IVSET)
  ! Creation of a list of GRID_VIEW encapsulating the layer of an input FIELD_VIEW field
  ! Given YLF dimensioned(NPROMA, NBLKS) as input,
  ! the output list size will contain one element, its view beeing dimensioned(NPROMA, NBLKS)
  TYPE (FIELD_VIEW), POINTER, INTENT (IN) :: YLF
  TYPE (GRID_VIEW), INTENT(INOUT) :: LG2RBV (:)
  TYPE (IVSET_PTR), INTENT(IN) :: IVSET
  CHARACTER(LEN=:), POINTER :: CNAME
  REAL(KIND=JPRB), POINTER :: ZZ2 (:,:)

  CALL ASSERT_DIM_ROLE(YLF, 1, FIELD_VIEW_DIM_ROLE%NPROMA, "LG2RB")
  CALL ASSERT_DIM_ROLE(YLF, 2, FIELD_VIEW_DIM_ROLE%BLOCK, "LG2RB")
  CALL FIELD_VIEW_GET_DATA_PTR(YLF, ZZ2)
  CALL FIELD_VIEW_GET_NAME_PTR(YLF, CNAME)

  IF (SIZE(LG2RBV) /= 1 ) CALL ABORT_TRANS("Error - incorrect size for LG2RBV")

  LG2RBV(1)%P => ZZ2(:,:)
  LG2RBV(1)%NAME => CNAME
  IF (ASSOCIATED(IVSET%PTR)) THEN
    LG2RBV (1)%IVSET = IVSET%PTR(1) - IVSET%BASE + 1
  ELSE
    LG2RBV (1)%IVSET = 1 ! default value when IVSET is not provided
  ENDIF
END SUBROUTINE LG2RB

SUBROUTINE LG3RB(LG3RBV,YLF,IVSET)
  ! Creation of a list of GRID_VIEW encapsulating the layers of an input FIELD_VIEW field
  ! Given YLF dimensioned(NPROMA, NLEVS, NBLKS) as input,
  ! the output list size will contain  (NLEVS) elements, their view beeing dimensioned(NPROMA, NBLKS)
  TYPE (FIELD_VIEW), POINTER, INTENT (IN) :: YLF
  TYPE (GRID_VIEW), INTENT(INOUT) :: LG3RBV (:)
  TYPE (IVSET_PTR), INTENT(IN) :: IVSET
  CHARACTER(LEN=:), POINTER :: CNAME
  CHARACTER(LEN=16) :: IVSET_SIZE_STR, LEVEL_SIZE_STR
  REAL(KIND=JPRB), POINTER :: ZZ3 (:,:,:)
  INTEGER(KIND=JPIM) :: JLEV, JCOUNT

  CALL ASSERT_DIM_ROLE(YLF, 1, FIELD_VIEW_DIM_ROLE%NPROMA, "LG3RB")
  CALL ASSERT_DIM_ROLE(YLF, 2, FIELD_VIEW_DIM_ROLE%LEVEL, "LG3RB")
  CALL ASSERT_DIM_ROLE(YLF, 3, FIELD_VIEW_DIM_ROLE%BLOCK, "LG3RB")
  CALL FIELD_VIEW_GET_DATA_PTR(YLF, ZZ3)
  CALL FIELD_VIEW_GET_NAME_PTR(YLF, CNAME)

  IF (SIZE(LG3RBV) /= SIZE (ZZ3, 2) ) CALL ABORT_TRANS("Error - incorrect size for LG3RBV")

  IF (ASSOCIATED(IVSET%PTR)) THEN
    IF (SIZE(IVSET%PTR) /= SIZE(ZZ3, 2)) THEN
      CALL TO_STR(SIZE(IVSET%PTR), IVSET_SIZE_STR)
      CALL TO_STR(SIZE(ZZ3, 2), LEVEL_SIZE_STR)
      CALL ABORT_TRANS("Error - LG3RB: incorrect size for IVSET: SIZE(IVSET) = " // TRIM(IVSET_SIZE_STR) &
        // " but SIZE(ZZ3, 2) = " // TRIM(LEVEL_SIZE_STR))
    END IF
  END IF

  JCOUNT = 1
  DO JLEV = LBOUND (ZZ3, 2), UBOUND (ZZ3, 2)
    LG3RBV (JCOUNT)%P => ZZ3 (:, JLEV, :)
    LG3RBV(JCOUNT)%NAME => CNAME
    IF (ASSOCIATED(IVSET%PTR)) THEN
      LG3RBV (JCOUNT)%IVSET = IVSET%PTR(JLEV) - IVSET%BASE + 1
    ELSE
      LG3RBV (JCOUNT)%IVSET = 1 ! default value when IVSET is not provided
    ENDIF
    JCOUNT = JCOUNT + 1
  ENDDO
END SUBROUTINE LG3RB

SUBROUTINE LG4RB(LG4RBV, YLF, IVSET)
  ! Creation of a list of GRID_VIEW encapsulating the layers of an input FIELD_VIEW field
  ! Given YLF dimensioned(NPROMA, NLEVS, NFIELDS, NBLKS) as input,
  ! the output list size will contain  (NLEVS*NFIELDS) elementa, their view beeing dimensioned(NPROMA, NBLKS)

  TYPE (FIELD_VIEW), INTENT(IN), POINTER :: YLF
  TYPE (GRID_VIEW), INTENT(INOUT) :: LG4RBV (:)
  TYPE (IVSET_PTR), INTENT(IN) :: IVSET
  CHARACTER(LEN=:), POINTER :: CNAME
  CHARACTER(LEN=16) :: IVSET_SIZE_STR, LEVEL_SIZE_STR
  REAL(KIND=JPRB), POINTER :: ZZ4 (:,:,:,:)

  INTEGER(KIND=JPIM) :: JLEV, JFLD, JCOUNT

  CALL ASSERT_DIM_ROLE(YLF, 1, FIELD_VIEW_DIM_ROLE%NPROMA, "LG4RB")
  CALL ASSERT_DIM_ROLE(YLF, 2, FIELD_VIEW_DIM_ROLE%LEVEL,  "LG4RB")
  CALL ASSERT_DIM_ROLE(YLF, 3, FIELD_VIEW_DIM_ROLE%FIELD,  "LG4RB")
  CALL ASSERT_DIM_ROLE(YLF, 4, FIELD_VIEW_DIM_ROLE%BLOCK,  "LG4RB")
  CALL FIELD_VIEW_GET_DATA_PTR(YLF, ZZ4)
  CALL FIELD_VIEW_GET_NAME_PTR(YLF, CNAME)

  IF (SIZE(LG4RBV) /= SIZE (ZZ4, 2) * SIZE (ZZ4, 3) ) CALL ABORT_TRANS("Error - incorrect size for LG4RBV")

  IF (ASSOCIATED(IVSET%PTR)) THEN
    IF (SIZE(IVSET%PTR) /= SIZE(ZZ4, 2)) THEN
      CALL TO_STR(SIZE(IVSET%PTR), IVSET_SIZE_STR)
      CALL TO_STR(SIZE(ZZ4, 2), LEVEL_SIZE_STR)
      CALL ABORT_TRANS("Error - LG4RB: incorrect size for IVSET: SIZE(IVSET) = " // TRIM(IVSET_SIZE_STR) &
        // " but SIZE(ZZ4, 2) = " // TRIM(LEVEL_SIZE_STR))
    END IF
  END IF

  JCOUNT = 1

  DO JFLD = LBOUND (ZZ4, 3), UBOUND (ZZ4, 3)
    DO JLEV = LBOUND (ZZ4, 2), UBOUND (ZZ4, 2)
      LG4RBV(JCOUNT)%P => ZZ4(:, JLEV, JFLD, :)
      LG4RBV(JCOUNT)%NAME => CNAME
      IF (ASSOCIATED(IVSET%PTR)) THEN
        LG4RBV (JCOUNT)%IVSET = IVSET%PTR(JLEV) - IVSET%BASE + 1
      ELSE
        LG4RBV (JCOUNT)%IVSET = 1 ! default value when IVSET is not provided
      ENDIF
      JCOUNT = JCOUNT + 1
    ENDDO
  ENDDO
END SUBROUTINE LG4RB

SUBROUTINE LG(YLFL,LGV,IVSET)
  ! Creation of a list of GRID_VIEW from a list YLFL of FIELD_VIEW
  ! For each field of YLFL, the IVSET of the matching spectral field can be provided
  ! through the optional IVSET argument. If IVSET is not provided, the IVSET of the
  ! generated GRID_VIEW is set to a default value (1).
  TYPE (FIELD_VIEW),TARGET, INTENT(IN) :: YLFL (:)      ! input list of FIELD_VIEW
  TYPE (GRID_VIEW), INTENT(INOUT) :: LGV (:) ! output list of GRID_VIEW
  TYPE (IVSET_PTR), INTENT(IN), OPTIONAL :: IVSET(:)

  TYPE (FIELD_VIEW), POINTER:: YLF
  TYPE (IVSET_PTR) :: IVSET_NULL
  INTEGER(KIND=JPIM) :: IOFF
  INTEGER(KIND=JPIM) :: ILEN, JFLD

  IF (PRESENT(IVSET)) THEN
    IF (SIZE(YLFL) /= SIZE(IVSET)) CALL ABORT_TRANS("LG FAILURE: SIZE(YLFL) /= SIZE(IVSET)")
  ENDIF

  IOFF = 0
  ILEN = -1

  ! iterate over YLFL LIST
  DO JFLD = 1, SIZE (YLFL)
  ! compute number of GRID_VIEW that will be generated for each field of the list
  ! In addition if LGV_PROVIDED: call the correct routine to create the GRID_VIEW for each field of the list
    YLF => YLFL (JFLD)
    SELECT CASE (YLF%RANK)
      CASE (1)
        ILEN = 1
      CASE (2)
        ILEN = 1
        IF (PRESENT(IVSET)) THEN
          CALL LG2RB(LGV(IOFF+1:IOFF+ILEN),YLF,IVSET(JFLD))
        ELSE
          CALL LG2RB(LGV(IOFF+1:IOFF+ILEN),YLF,IVSET_NULL)
        ENDIF
      CASE(3)
        ILEN = FIELD_VIEW_GET_EXTENT(YLF, 2)
        IF (PRESENT(IVSET)) THEN
          CALL LG3RB(LGV (IOFF+1:IOFF+ILEN),YLF,IVSET(JFLD))
        ELSE
          CALL LG3RB(LGV (IOFF+1:IOFF+ILEN),YLF,IVSET_NULL)
        ENDIF
      CASE(4)
        ILEN = FIELD_VIEW_GET_EXTENT(YLF, 2) * FIELD_VIEW_GET_EXTENT(YLF, 3)
        IF (PRESENT(IVSET)) THEN
          CALL LG4RB(LGV (IOFF+1:IOFF+ILEN),YLF,IVSET(JFLD))
        ELSE
          CALL LG4RB(LGV (IOFF+1:IOFF+ILEN),YLF,IVSET_NULL)
        ENDIF
      CASE DEFAULT
        CALL ABORT_TRANS("LG FAILURE: CLASS UNKNOWN")
    END SELECT
    IOFF = IOFF + ILEN
  ENDDO

  IF (SIZE(LGV) /= IOFF)  CALL ABORT_TRANS("LG FAILURE: LGV has incorrect size")

END SUBROUTINE LG

