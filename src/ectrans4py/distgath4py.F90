! Distributed-memory data movement: scatter a global field (on the 'from' task,
! 1-based MPL rank) to the local partitions, and gather back. Multi-field (KFLD).
! Single precision (JPRB = real32). KFROM/KTO give the source/dest MPL rank per field.
! KRESOL, the last argument of every routine below, is the resolution tag returned by
! SETUP_TRANS_4PY, and the data are distributed or gathered on that resolution. A KRESOL
! that is not a resolution set up by SETUP_TRANS_4PY returns error code 101, and a
! grid-point-only resolution (SETUP_TRANS_4PY LDGRIDONLY) error code 102 for the spectral
! fields (RESOL_CHECK4PY_MOD).
! Grid-point arrays that ecTrans reads or writes whole are declared (KGPTOT, KFLD, 1),
! ecTrans's NPROMA-blocked layout with a single block: the same memory as (KGPTOT, KFLD),
! so they are passed to ecTrans without a copy.

SUBROUTINE DIST_SPEC4PY(KRETURNCODE, KSPEC2G, KSPEC2, KFLD, KFROM, PSPECG, PSPEC, KRESOL)
! Global spectral PSPECG(KSPEC2G,KFLD) on KFROM -> local PSPEC(KSPEC2,KFLD).
USE ISO_FORTRAN_ENV, ONLY: INT64
USE PARKIND1, ONLY: JPIM, JPRB
USE RESOL_CHECK4PY_MOD, ONLY: RESOL_STATUS
IMPLICIT NONE
INTEGER(KIND=INT64), INTENT(OUT) :: KRETURNCODE
INTEGER(KIND=INT64), INTENT(IN)  :: KSPEC2G, KSPEC2, KFLD, KRESOL
INTEGER(KIND=INT64), DIMENSION(KFLD), INTENT(IN) :: KFROM
REAL(KIND=JPRB), DIMENSION(KSPEC2G, KFLD), INTENT(IN)  :: PSPECG
REAL(KIND=JPRB), DIMENSION(KSPEC2, KFLD),  INTENT(OUT) :: PSPEC
INTEGER(KIND=JPIM) :: IFROM(KFLD)
#include "dist_spec.h"
KRETURNCODE = RESOL_STATUS(KRESOL)
IF (KRETURNCODE /= 0) RETURN
IFROM(:) = INT(KFROM(:), JPIM)
CALL DIST_SPEC(PSPECG=PSPECG, KFDISTG=INT(KFLD,JPIM), KFROM=IFROM, PSPEC=PSPEC, &
 & LDIM1_IS_FLD=.FALSE., KRESOL=INT(KRESOL,JPIM))
END SUBROUTINE DIST_SPEC4PY


