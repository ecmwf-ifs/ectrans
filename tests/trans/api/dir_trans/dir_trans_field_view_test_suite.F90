INTEGER FUNCTION ECTRANS_TEST_TRANS_API_DIR_TRANS_FV_CALL_MODE_1_SCALAR_1() RESULT(KRET) &
  & BIND(C, NAME="ectrans_test_trans_api_dir_trans_field_view_call_mode_1_scalar_1")
  REAL(KIND=JPRB), ALLOCATABLE, TARGET :: ZGP(:,:,:), ZSPSCALAR(:,:)
  INTEGER(KIND=JPIM) :: ISPEC2, IGPTOTG, IGPTOT, IMY_PROC, IGPBLKS, I_REGIONS_NS, I_REGIONS_EW

  CALL SETUP_TEST(ISPEC2, IGPTOTG, IGPTOT, IGPBLKS, IMY_PROC, I_REGIONS_NS, I_REGIONS_EW)
  ZGP = GET_INPUT_FIELD(IMY_PROC, IGPTOTG, IGPBLKS, 1)
  ALLOCATE(ZSPSCALAR(1,ISPEC2))

  CALL DIR_TRANS_FIELD_VIEW( &
    & KRESOL=IRESOL_1, &
    & YDGPSCALAR=[MAKE_FIELD_VIEW(ZGP(:,1,:), FIELD_VIEW_INDEXING%NPROMA_BLOCK, GRID_SCALAR_NAME, INTENT_IN)], &
    & YDGPU=EMPTY_FIELD_VIEW_LIST, &
    & YDGPV=EMPTY_FIELD_VIEW_LIST, &
    & YDSPSCALAR=[MAKE_FIELD_VIEW(ZSPSCALAR, FIELD_VIEW_INDEXING%LEVEL_SPEC2, SPEC_SCALAR_NAME, INTENT_OUT)], &
    & YDSPVOR=EMPTY_FIELD_VIEW_LIST, &
    & YDSPDIV=EMPTY_FIELD_VIEW_LIST)

  IF (HAVE_M0_MODE()) THEN
    KRET = MERGE(0, 1, APPROX_EQ(ZSPSCALAR(1,1), 1.0_JPRB) .AND. &
      &         ALL(APPROX_EQ(ZSPSCALAR(1,2:), 0.0_JPRB)))
  ELSE
    KRET = MERGE(0, 1, ALL(APPROX_EQ(ZSPSCALAR, 0.0_JPRB)))
  ENDIF

  IF (LUSE_MPI) CALL MPL_ALLREDUCE(KRET, CDOPER="MAX")

  DEALLOCATE(ZSPSCALAR, ZGP)
  CALL CLEANUP_TEST
END FUNCTION ECTRANS_TEST_TRANS_API_DIR_TRANS_FV_CALL_MODE_1_SCALAR_1

INTEGER FUNCTION ECTRANS_TEST_TRANS_API_DIR_TRANS_FV_CALL_MODE_1_WIND_1() RESULT(KRET) &
  & BIND(C, NAME="ectrans_test_trans_api_dir_trans_field_view_call_mode_1_wind_1")
  REAL(KIND=JPRB), ALLOCATABLE, TARGET :: ZGP(:,:,:), ZSPVOR(:,:), ZSPDIV(:,:)
  INTEGER(KIND=JPIM) :: ISPEC2, IGPTOTG, IGPTOT, IMY_PROC, IGPBLKS, I_REGIONS_NS, I_REGIONS_EW
  REAL(KIND=JPRB) :: ZCORRECT_VORTICITY_VALUE

  CALL SETUP_TEST(ISPEC2, IGPTOTG, IGPTOT, IGPBLKS, IMY_PROC, I_REGIONS_NS, I_REGIONS_EW)
  ZGP = ROTATIONAL_WIND(IGPBLKS, I_REGIONS_NS, I_REGIONS_EW)
  ALLOCATE(ZSPVOR(1,ISPEC2), ZSPDIV(1,ISPEC2))

  CALL DIR_TRANS_FIELD_VIEW( &
    & KRESOL=IRESOL_1, &
    & YDGPSCALAR=EMPTY_FIELD_VIEW_LIST, &
    & YDGPU=[MAKE_FIELD_VIEW(ZGP(:,1,:), FIELD_VIEW_INDEXING%NPROMA_BLOCK, GRID_U_NAME, INTENT_IN)], &
    & YDGPV=[MAKE_FIELD_VIEW(ZGP(:,2,:), FIELD_VIEW_INDEXING%NPROMA_BLOCK, GRID_V_NAME, INTENT_IN)], &
    & YDSPSCALAR=EMPTY_FIELD_VIEW_LIST, &
    & YDSPVOR=[MAKE_FIELD_VIEW(ZSPVOR, FIELD_VIEW_INDEXING%LEVEL_SPEC2, SPEC_VOR_NAME, INTENT_OUT)], &
    & YDSPDIV=[MAKE_FIELD_VIEW(ZSPDIV, FIELD_VIEW_INDEXING%LEVEL_SPEC2, SPEC_DIV_NAME, INTENT_OUT)])

  IF (HAVE_M0_MODE()) THEN
    ZCORRECT_VORTICITY_VALUE = 2.0_JPRB * SQRT(1.0_JPRB / 3.0_JPRB) / PPEARTH_RADIUS
    KRET = 0
    IF (ANY(.NOT. APPROX_EQ(ZSPDIV, 0.0_JPRB))) KRET = 1
    IF (ANY(.NOT. APPROX_EQ(ZSPVOR(1,1:2), 0.0_JPRB))) KRET = 1
    IF (.NOT. APPROX_EQ(ZSPVOR(1,3), ZCORRECT_VORTICITY_VALUE)) KRET = 1
  ELSE
    KRET = MERGE(0, 1, ALL(APPROX_EQ(ZSPVOR, 0.0_JPRB) .AND. ALL(APPROX_EQ(ZSPDIV, 0.0_JPRB))))
  ENDIF

  IF (LUSE_MPI) CALL MPL_ALLREDUCE(KRET, CDOPER="MAX")

  DEALLOCATE(ZSPDIV, ZSPVOR, ZGP)
  CALL CLEANUP_TEST
END FUNCTION ECTRANS_TEST_TRANS_API_DIR_TRANS_FV_CALL_MODE_1_WIND_1

INTEGER FUNCTION ECTRANS_TEST_TRANS_API_DIR_TRANS_FV_CALL_MODE_1_WIND_1_SCALAR_1() RESULT(KRET) &
  & BIND(C, NAME="ectrans_test_trans_api_dir_trans_field_view_call_mode_1_wind_1_scalar_1")
  REAL(KIND=JPRB), ALLOCATABLE, TARGET :: ZGP(:,:,:), ZSPVOR(:,:), ZSPDIV(:,:), ZSPSCALAR(:,:)
  INTEGER(KIND=JPIM) :: ISPEC2, IGPTOTG, IGPTOT, IMY_PROC, IGPBLKS, I_REGIONS_NS, I_REGIONS_EW
  REAL(KIND=JPRB) :: ZCORRECT_VORTICITY_VALUE

  CALL SETUP_TEST(ISPEC2, IGPTOTG, IGPTOT, IGPBLKS, IMY_PROC, I_REGIONS_NS, I_REGIONS_EW)
  ALLOCATE(ZGP(JPPROMA, 3, IGPBLKS))
  ALLOCATE(ZSPVOR(1,ISPEC2), ZSPDIV(1,ISPEC2), ZSPSCALAR(1,ISPEC2))
  ZGP(:,1:2,:) = ROTATIONAL_WIND(IGPBLKS, I_REGIONS_NS, I_REGIONS_EW)
  ZGP(:,3:3,:) = GET_INPUT_FIELD(IMY_PROC, IGPTOTG, IGPBLKS, 1)

  CALL DIR_TRANS_FIELD_VIEW( &
    & KRESOL=IRESOL_1, &
    & YDGPSCALAR=[MAKE_FIELD_VIEW(ZGP(:,3,:), FIELD_VIEW_INDEXING%NPROMA_BLOCK, GRID_SCALAR_NAME, INTENT_IN)], &
    & YDGPU=[MAKE_FIELD_VIEW(ZGP(:,1,:), FIELD_VIEW_INDEXING%NPROMA_BLOCK, GRID_U_NAME, INTENT_IN)], &
    & YDGPV=[MAKE_FIELD_VIEW(ZGP(:,2,:), FIELD_VIEW_INDEXING%NPROMA_BLOCK, GRID_V_NAME, INTENT_IN)], &
    & YDSPSCALAR=[MAKE_FIELD_VIEW(ZSPSCALAR, FIELD_VIEW_INDEXING%LEVEL_SPEC2, SPEC_SCALAR_NAME, INTENT_OUT)], &
    & YDSPVOR=[MAKE_FIELD_VIEW(ZSPVOR, FIELD_VIEW_INDEXING%LEVEL_SPEC2, SPEC_VOR_NAME, INTENT_OUT)], &
    & YDSPDIV=[MAKE_FIELD_VIEW(ZSPDIV, FIELD_VIEW_INDEXING%LEVEL_SPEC2, SPEC_DIV_NAME, INTENT_OUT)])

  IF (HAVE_M0_MODE()) THEN
    ZCORRECT_VORTICITY_VALUE = 2.0_JPRB * SQRT(1.0_JPRB / 3.0_JPRB) / PPEARTH_RADIUS
    KRET = 0
    IF (.NOT. ALL(APPROX_EQ(ZSPSCALAR(1,2:), 0.0_JPRB))) KRET = 1
    IF (.NOT. APPROX_EQ(ZSPSCALAR(1,1), 1.0_JPRB)) KRET = 1
    IF (ANY(.NOT. APPROX_EQ(ZSPDIV, 0.0_JPRB))) KRET = 1
    IF (ANY(.NOT. APPROX_EQ(ZSPVOR(1,1:2), 0.0_JPRB))) KRET = 1
    IF (.NOT. APPROX_EQ(ZSPVOR(1,3), ZCORRECT_VORTICITY_VALUE)) KRET = 1
  ELSE
    IF (ALL(APPROX_EQ(ZSPVOR, 0.0_JPRB)) .AND. ALL(APPROX_EQ(ZSPDIV, 0.0_JPRB)) .AND. &
      & ALL(APPROX_EQ(ZSPSCALAR, 0.0_JPRB))) THEN
      KRET = 0
    ELSE
      KRET = 1
    END IF
  ENDIF

  IF (LUSE_MPI) CALL MPL_ALLREDUCE(KRET, CDOPER="MAX")

  DEALLOCATE(ZSPSCALAR, ZSPDIV, ZSPVOR, ZGP)
  CALL CLEANUP_TEST
END FUNCTION ECTRANS_TEST_TRANS_API_DIR_TRANS_FV_CALL_MODE_1_WIND_1_SCALAR_1

