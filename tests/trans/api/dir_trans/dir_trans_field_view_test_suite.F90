  REAL(KIND=JPRB), ALLOCATABLE, TARGET :: ZGPUV(:,:,:,:), ZSPVOR(:,:), ZSPDIV(:,:)
  INTEGER(KIND=JPIM) :: ISPEC2, IGPTOTG, IGPTOT, IMY_PROC, IGPBLKS, I_REGIONS_NS, I_REGIONS_EW
  REAL(KIND=JPRB) :: ZCORRECT_VORTICITY_VALUE

  CALL SETUP_TEST(ISPEC2, IGPTOTG, IGPTOT, IGPBLKS, IMY_PROC, I_REGIONS_NS, I_REGIONS_EW)
  ALLOCATE(ZGPUV(JPPROMA,1,2,IGPBLKS))
  ZGPUV(:,1,:,:) = ROTATIONAL_WIND(IGPBLKS, I_REGIONS_NS, I_REGIONS_EW)
  ALLOCATE(ZSPVOR(1,ISPEC2), ZSPDIV(1,ISPEC2))

  CALL DIR_TRANS_FIELD_VIEW( &
    & KRESOL=IRESOL_1, &
    & YDGPSCALAR=EMPTY_FIELD_VIEW_LIST, &
    & YDGPU=[MAKE_FIELD_VIEW(ZGPUV(:,:,1,:), FIELD_VIEW_INDEXING%NPROMA_LEVEL_BLOCK, GRID_U_NAME, INTENT_IN)], &
    & YDGPV=[MAKE_FIELD_VIEW(ZGPUV(:,:,2,:), FIELD_VIEW_INDEXING%NPROMA_LEVEL_BLOCK, GRID_V_NAME, INTENT_IN)], &
    & YDSPSCALAR=EMPTY_FIELD_VIEW_LIST, &
    & YDSPVOR=[MAKE_FIELD_VIEW(ZSPVOR, FIELD_VIEW_INDEXING%LEVEL_SPEC2, SPEC_VOR_NAME, INTENT_OUT)], &
    & YDSPDIV=[MAKE_FIELD_VIEW(ZSPDIV, FIELD_VIEW_INDEXING%LEVEL_SPEC2, SPEC_DIV_NAME, INTENT_OUT)])

  IF (HAVE_M0_MODE()) THEN
    ZCORRECT_VORTICITY_VALUE = 2.0_JPRB * SQRT(1.0_JPRB / 3.0_JPRB) / PPEARTH_RADIUS
    KRET = 0
    IF (ANY(.NOT. APPROX_EQ(ZSPDIV, 0.0_JPRB))) KRET = 1
    IF (ANY(.NOT. APPROX_EQ(ZSPVOR(1,1:2), 0.0_JPRB))) KRET = 1
    IF (.NOT. APPROX_EQ(ZSPVOR(1,3), ZCORRECT_VORTICITY_VALUE)) KRET = 1
  ELSE
    KRET = MERGE(0, 1, ALL(APPROX_EQ(ZSPVOR, 0.0_JPRB) .AND. ALL(APPROX_EQ(ZSPDIV, 0.0_JPRB))))
  ENDIF

  IF (LUSE_MPI) CALL MPL_ALLREDUCE(KRET, CDOPER="MAX")

  DEALLOCATE(ZSPDIV, ZSPVOR, ZGPUV)
  CALL CLEANUP_TEST
END FUNCTION ECTRANS_TEST_TRANS_API_DIR_TRANS_FV_CALL_MODE_2_WIND_1

END MODULE DIR_TRANS_FIELD_VIEW_TEST_SUITE
