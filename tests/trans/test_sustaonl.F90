PROGRAM TEST_SUSTAONL

USE EC_PARKIND, ONLY: JPIM, JPRD
USE SUSTAONL_MOD, ONLY: SELECT_LONGITUDE_POINTS

IMPLICIT NONE

INTEGER(JPIM) :: J, LOENS(16), FIRST(16), SIZES(3)

! Ties between rows and half-integer rounding.
CALL CHECK_PARTITION([1,1,1],[7,128,256],360000._JPRD/REAL([7,128,256],JPRD),[0,1,129,261])
! Partial rows, exhausted rows and an empty region.
CALL CHECK_PARTITION([3,10,6,1],[7,9,15,0],360000._JPRD/REAL([7,10,17,1],JPRD),[2,0,6,7])
! Several points in a row can have the same rounded longitude.
CALL CHECK_PARTITION([1,1,1],[5,6,7],[0.5_JPRD,0.75_JPRD,1._JPRD],[1,3,0,14])

! An O8 grid split into three regions with unequal point counts.
DO J = 1,SIZE(LOENS)
  LOENS(J) = 20+4*(MIN(J,SIZE(LOENS)+1-J)-1)
ENDDO
FIRST = 1
SIZES = SUM(LOENS)/SIZE(SIZES)
SIZES(1:MOD(SUM(LOENS),SIZE(SIZES))) = SIZES(1:MOD(SUM(LOENS),SIZE(SIZES)))+1
CALL CHECK_PARTITION(FIRST,LOENS,360000._JPRD/REAL(LOENS,JPRD),SIZES)

CONTAINS

SUBROUTINE CHECK_PARTITION(START,FINISH,DIVID,COUNTS)
  INTEGER(JPIM), INTENT(IN) :: START(:),FINISH(:),COUNTS(:)
  REAL(JPRD), INTENT(IN) :: DIVID(:)
  INTEGER(JPIM) :: NEXT(SIZE(START)),REFNEXT(SIZE(START)),TAKE(SIZE(START)),REF_TAKE(SIZE(START))
  INTEGER(JPIM) :: STA(SIZE(START)),REFSTA(SIZE(START)),REGION

  NEXT = START
  REFNEXT = START
  DO REGION = 1,SIZE(COUNTS)
    CALL SELECT_LONGITUDE_POINTS(NEXT,FINISH,DIVID,COUNTS(REGION),TAKE)
    CALL REFERENCE_SELECT(REFNEXT,FINISH,DIVID,COUNTS(REGION),REF_TAKE)
    IF (SUM(TAKE)/=COUNTS(REGION)) ERROR STOP 'Incorrect region point count'
    IF (ANY(TAKE<0).OR.ANY(TAKE>MAX(0,FINISH-NEXT+1))) ERROR STOP 'Invalid latitude point count'
    STA = 0
    REFSTA = 0
    WHERE(TAKE>0) STA = NEXT
    WHERE(REF_TAKE>0) REFSTA = REFNEXT
    IF (ANY(STA/=REFSTA).OR.ANY(TAKE/=REF_TAKE)) ERROR STOP 'NSTA/NONL differ from the original partition'
    NEXT = NEXT+TAKE
    REFNEXT = REFNEXT+REF_TAKE
  ENDDO
  IF (ANY(NEXT/=MAX(START,FINISH+1))) ERROR STOP 'Unassigned grid points'
END SUBROUTINE CHECK_PARTITION

! Original SUSTAONL point-by-point selection.
SUBROUTINE REFERENCE_SELECT(START,FINISH,DIVID,POINTS,TAKE)
  INTEGER(JPIM), INTENT(IN) :: START(:),FINISH(:),POINTS
  REAL(JPRD), INTENT(IN) :: DIVID(:)
  INTEGER(JPIM), INTENT(OUT) :: TAKE(SIZE(START))
  INTEGER(JPIM) :: NEXT(SIZE(START)),P,J,ANGLE,KEY,ROW

  NEXT = START
  TAKE = 0
  DO P = 1,POINTS
    ANGLE = 360000
    DO J = 1,SIZE(START)
      IF (NEXT(J)<=FINISH(J)) THEN
        KEY = NINT(REAL(NEXT(J)-1,JPRD)*DIVID(J))
        IF (KEY<ANGLE) THEN
          ANGLE = KEY
          ROW = J
        ENDIF
      ENDIF
    ENDDO
    TAKE(ROW) = TAKE(ROW)+1
    NEXT(ROW) = NEXT(ROW)+1
  ENDDO
END SUBROUTINE REFERENCE_SELECT

END PROGRAM TEST_SUSTAONL
